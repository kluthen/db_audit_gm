SELECT CASE WHEN w.o > 0 THEN 'Etc/GMT-' || w.o
            WHEN w.o < 0 THEN 'Etc/GMT+' || -w.o
            ELSE 'Etc/GMT' END AS close_zone
  FROM (SELECT CASE WHEN s.m > 14 THEN s.m - 24 WHEN s.m < -12 THEN s.m + 24 ELSE s.m END AS o
          FROM (SELECT (:customer_utc_offset) + (:close_offset) AS m) s) w \gset

