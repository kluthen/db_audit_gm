-- gmctl load-data streams this file into
--   psql -X -q -v ON_ERROR_STOP=1 -d postgres
-- run as the postgres OS user (capture W3-A); the file creates its own
-- roles and database. Deterministic: the same rows at every load.
--
-- Stands for the backup the customer's contractor restored onto the new
-- server. Healthy as restored: the state faults (gmctl inject) change it
-- afterwards, so do not plant anything here.

-- Roles: the owner of the schema (no login) and the application's login.
CREATE ROLE bookshop NOLOGIN;
CREATE ROLE shop_app LOGIN PASSWORD 'Pages-and-Co-2019';
CREATE DATABASE bookshop OWNER bookshop;
REVOKE ALL ON DATABASE bookshop FROM PUBLIC;
GRANT CONNECT, TEMPORARY ON DATABASE bookshop TO shop_app;

\connect bookshop
SET ROLE bookshop;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;

CREATE TABLE customers (
    id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       text        NOT NULL UNIQUE,
    full_name   text        NOT NULL,
    city        text        NOT NULL,
    created_at  timestamptz NOT NULL
);

CREATE TABLE books (
    id          integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn        text          NOT NULL UNIQUE,
    title       text          NOT NULL,
    author      text          NOT NULL,
    price       numeric(8,2)  NOT NULL CHECK (price >= 0),
    stock       integer       NOT NULL CHECK (stock >= 0)
);

CREATE TABLE orders (
    id          integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer       NOT NULL REFERENCES customers (id),
    placed_at   timestamptz   NOT NULL,
    status      text          NOT NULL
                CHECK (status IN ('new', 'paid', 'shipped', 'delivered', 'cancelled')),
    total       numeric(10,2) NOT NULL
);

CREATE TABLE order_lines (
    id          integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    integer       NOT NULL REFERENCES orders (id),
    book_id     integer       NOT NULL REFERENCES books (id),
    quantity    integer       NOT NULL CHECK (quantity > 0),
    unit_price  numeric(8,2)  NOT NULL
);

