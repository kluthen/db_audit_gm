-- Restored-backup data of the fernway-clinics-monitoring scenario's db node.
-- gmctl load-data streams this file into
--   psql -X -q -v ON_ERROR_STOP=1 -d postgres
-- run as the postgres OS user; the file creates its own roles and
-- database. Deterministic: the same rows at every load.
--
-- Stands for Fernway's booking database as it is in production. Healthy as
-- restored: the state faults (gmctl inject) change it afterwards, so do not
-- plant anything here. About 50 000 rows, a few megabytes.

-- Roles: the owner of the schema (no login) and the booking site's login.
CREATE ROLE fernway NOLOGIN;
CREATE ROLE clinic_app LOGIN PASSWORD 'Fernway-Booking-2021';
CREATE DATABASE clinic OWNER fernway;
REVOKE ALL ON DATABASE clinic FROM PUBLIC;
GRANT CONNECT, TEMPORARY ON DATABASE clinic TO clinic_app;

\connect clinic
SET ROLE fernway;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;

CREATE TABLE clinics (
    id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text        NOT NULL UNIQUE,
    town        text        NOT NULL
);

CREATE TABLE vets (
    id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinic_id   integer     NOT NULL REFERENCES clinics (id),
    full_name   text        NOT NULL
);

CREATE TABLE owners (
    id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       text        NOT NULL UNIQUE,
    full_name   text        NOT NULL,
    phone       text        NOT NULL,
    created_at  timestamptz NOT NULL
);

CREATE TABLE pets (
    id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    integer     NOT NULL REFERENCES owners (id),
    name        text        NOT NULL,
    species     text        NOT NULL
                CHECK (species IN ('dog', 'cat', 'rabbit', 'bird', 'horse', 'other')),
    born_on     date
);

CREATE TABLE appointments (
    id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id      integer     NOT NULL REFERENCES pets (id),
    vet_id      integer     NOT NULL REFERENCES vets (id),
    clinic_id   integer     NOT NULL REFERENCES clinics (id),
    starts_at   timestamptz NOT NULL,
    minutes     integer     NOT NULL CHECK (minutes > 0),
    status      text        NOT NULL
                CHECK (status IN ('booked', 'confirmed', 'done', 'no-show', 'cancelled')),
    reason      text        NOT NULL
);

