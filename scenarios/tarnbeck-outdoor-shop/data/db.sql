INSERT INTO daily_sales (day, orders, revenue)
SELECT placed_at::date, count(*), sum(total)
  FROM orders WHERE placed_at < current_date GROUP BY 1;

CREATE INDEX orders_customer_id_idx ON orders (customer_id);
