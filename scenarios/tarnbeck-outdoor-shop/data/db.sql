UPDATE customers c SET last_order_at = s.last_order_at, lifetime_value = s.total
  FROM (SELECT customer_id, max(placed_at) AS last_order_at,
               sum(total) FILTER (WHERE status = 'invoiced') AS total
          FROM orders GROUP BY customer_id) s
 WHERE c.id = s.customer_id;

UPDATE products p SET sold = s.quantity
  FROM (SELECT product_id, sum(quantity) AS quantity FROM order_lines GROUP BY product_id) s
 WHERE p.id = s.product_id;

