-- 300 000 orders over the last fifteen days, one every 4.32 s, each with
-- one to five lines (900 000 lines); the newest are still being packed and
-- shipped, the rest invoiced.
INSERT INTO orders (id, customer_id, placed_at, status, total, updated_at)
SELECT g, 1 + (g::bigint * 7919) % 20000, t.placed_at,
       CASE WHEN g <= 280000 THEN 'invoiced' WHEN g <= 290000 THEN 'shipped'
            WHEN g <= 295000 THEN 'packed' ELSE 'paid' END,
       b.total, t.placed_at
  FROM generate_series(1, 300000) AS g
 CROSS JOIN LATERAL (SELECT now() - interval '15 days' + g * interval '4.32 seconds' AS placed_at) AS t
 CROSS JOIN LATERAL (
       SELECT sum((1 + (g + k) % 3) * p.price) AS total
         FROM generate_series(1, 1 + g % 5) AS k
         JOIN products p ON p.id = 1 + (g * 31 + k * 97) % 2000) AS b;
SELECT setval(pg_get_serial_sequence('orders', 'id'), 300000);

