-- of the shop's database, restored onto the new server. gmctl load-data
-- streams this file into
--   psql -X -q -v ON_ERROR_STOP=1 -d postgres
-- run as the postgres OS user; the file creates its own roles and database.
-- The two application roles log in; their passwords are the game's
-- secrets, set by load-data, never written here.
CREATE ROLE shop NOLOGIN;
CREATE ROLE shop_app LOGIN;        -- the web shop (orders, catalogue, carriers' feed, close of day)
CREATE ROLE shop_reports LOGIN;    -- the back office (dashboards, reports, roll-up, accounting export)
CREATE DATABASE shop OWNER shop;

\connect shop
SET ROLE shop;

CREATE TABLE customers (
    id             integer       PRIMARY KEY,
    name           text          NOT NULL,
    email          text          NOT NULL,
    created_at     timestamptz   NOT NULL,
    last_order_at  timestamptz,
    lifetime_value numeric(12,2) NOT NULL DEFAULT 0
);

CREATE TABLE products (
    id       integer       PRIMARY KEY,
    sku      text          NOT NULL UNIQUE,
    name     text          NOT NULL,
    category text          NOT NULL,
    price    numeric(10,2) NOT NULL,
    stock    integer       NOT NULL,
    sold     integer       NOT NULL DEFAULT 0
);

CREATE TABLE orders (
    id          integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer       NOT NULL REFERENCES customers (id),
    placed_at   timestamptz   NOT NULL,
    status      text          NOT NULL,   -- paid, packed, shipped, invoiced
    total       numeric(10,2) NOT NULL,
    updated_at  timestamptz   NOT NULL
);

CREATE TABLE order_lines (
    id           bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     integer       NOT NULL REFERENCES orders (id),
    product_id   integer       NOT NULL REFERENCES products (id),
    sku          text          NOT NULL,   -- the product as sold
    product_name text          NOT NULL,
    quantity     integer       NOT NULL,
    unit_price   numeric(10,2) NOT NULL,
    vat_rate     numeric(4,2)  NOT NULL,
    line_total   numeric(10,2) NOT NULL,
    created_at   timestamptz   NOT NULL
);

-- The carriers' delivery events, stored as received.
CREATE TABLE delivery_events (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    uuid        NOT NULL,     -- the carrier's id of the event
    order_id    integer     NOT NULL,
    status      text        NOT NULL,
    received_at timestamptz NOT NULL
);

CREATE TABLE daily_sales (
    day     date          PRIMARY KEY,
    orders  integer       NOT NULL,
    revenue numeric(14,2) NOT NULL
);

