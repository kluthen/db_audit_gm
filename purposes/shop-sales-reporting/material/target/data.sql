-- The sales reporting purpose's target (v0.4 master spec 10.1, 9.6, 9.7;
-- access model 9.1, 9.2): the BI agency's reporting instance, Lumen
-- Analytics'. Copied into a scenario, this file makes (or is appended to)
-- the target node's data file, which gmctl load-data streams into
--   psql -X -q -v ON_ERROR_STOP=1 -d postgres
-- run as the postgres OS user, with the psql variables customer_timezone
-- (the bare zone, Etc/GMT-2 for UTC+2) and customer_utc_offset (2, -5, 0).
-- The file creates its own roles and database (capture W1, item 0: top-level
-- CREATE ROLE and CREATE DATABASE lines). The login roles' passwords are the
-- game's secrets, set by load-data, never written here; so is the user
-- mapping's password, from its remote role's secret (master spec 8.6, 14).
--
-- Written for the first v0.4 scenario's names: the source is db:5432/shop
-- (the foreign server's options), the target this node's database
-- reporting. The GM adapts them as it copies.
\if :{?customer_timezone}
\else
DO $$ BEGIN RAISE EXCEPTION 'reporting data: psql variable customer_timezone is not set '
                            '(gmctl load-data passes -v customer_timezone=<zone>)'; END $$;
\endif
\if :{?customer_utc_offset}
\else
DO $$ BEGIN RAISE EXCEPTION 'reporting data: psql variable customer_utc_offset is not set '
                            '(gmctl load-data passes -v customer_utc_offset=<hours>)'; END $$;
\endif

CREATE ROLE reporting NOLOGIN;     -- owns the agency's tables and the nightly close
CREATE ROLE bi_etl LOGIN;          -- the hourly script's target; the nightly close's CALL
CREATE ROLE bi_reader LOGIN;       -- the back office's dashboards
CREATE DATABASE reporting OWNER reporting;

\connect reporting

-- postgres_fdw ships with the server; created as superuser (master spec 8.6).
CREATE EXTENSION IF NOT EXISTS postgres_fdw;

SET ROLE reporting;

CREATE SCHEMA rpt;                 -- what the agency publishes
CREATE SCHEMA src;                 -- the source's tables, as foreign tables

-- The customer's zone and offset, one row from load-data's variables, as the
-- shop's own business_settings holds them (master spec 8.5, 9.2): the
-- nightly close cuts its day in this zone, the hourly script its hours.
CREATE TABLE rpt.business_settings (
    timezone         text    NOT NULL,   -- Etc/GMT-N for UTC+N
    utc_offset_hours integer NOT NULL
);
CREATE UNIQUE INDEX business_settings_one_row ON rpt.business_settings ((true));
INSERT INTO rpt.business_settings (timezone, utc_offset_hours)
VALUES (:'customer_timezone', :customer_utc_offset);

-- The run ledger both jobs write themselves, inside the transaction that
-- publishes: job (rollup-hourly, rollup-close), when it ran, the source
-- rows it read, the rows it wrote, and for the hourly script the
-- watermark (the source's time up to which it read the changed orders);
-- for the close, the end of the day it closed.
CREATE TABLE rpt.etl_runs (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job          text        NOT NULL,
    started_at   timestamptz NOT NULL,
    finished_at  timestamptz,
    rows_read    bigint,
    rows_written bigint,
    watermark    timestamptz
);

-- The published figures: aggregates only, no customer id. A local hour or
-- day is the customer's (the source's business_settings zone); run_id is
-- the run that last wrote the row (for a closed day, the close that closed
-- it: the hourly script then keeps its orders and revenue and updates only
-- its invoiced revenue).
CREATE TABLE rpt.sales_hourly (
    hour_local timestamp     NOT NULL,   -- the local hour's start
    category   text          NOT NULL,
    orders     integer       NOT NULL,   -- orders with a line in the category
    units      integer       NOT NULL,
    revenue    numeric(14,2) NOT NULL,   -- the lines' totals
    run_id     bigint        NOT NULL REFERENCES rpt.etl_runs (id),
    PRIMARY KEY (hour_local, category)
);

CREATE TABLE rpt.sales_daily (
    day_local        date          PRIMARY KEY,
    orders           integer       NOT NULL,
    revenue          numeric(14,2) NOT NULL,   -- the orders' totals
    invoiced_revenue numeric(14,2) NOT NULL,   -- the totals of the orders invoiced so far
    closed           boolean       NOT NULL DEFAULT false,   -- set by the nightly close
    run_id           bigint        NOT NULL REFERENCES rpt.etl_runs (id)
);
CREATE INDEX sales_hourly_run_id_idx ON rpt.sales_hourly (run_id);
CREATE INDEX sales_daily_run_id_idx ON rpt.sales_daily (run_id);

-- The nightly close (rollup-close, 01:30 customer time, run from bi as
-- bi_etl): yesterday in the customer's zone, its hours and its day
-- recomputed whole from the source over postgres_fdw and the day marked
-- closed, one rpt.etl_runs row. SECURITY INVOKER: it reads the source as
-- its caller's user mapping allows, nothing more. One set-based statement
-- per table, computed on this instance (master spec 8.7).
CREATE PROCEDURE rpt.close_day()
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    tz      text;
    closing date;
    lo      timestamptz;
    hi      timestamptz;
    run     bigint;
    n_hours bigint;
    n_read  bigint;
BEGIN
    SELECT timezone INTO STRICT tz FROM rpt.business_settings;
    closing := (now() AT TIME ZONE tz)::date - 1;
    lo := closing::timestamp AT TIME ZONE tz;
    hi := (closing + 1)::timestamp AT TIME ZONE tz;

    INSERT INTO rpt.etl_runs (job, started_at, watermark)
    VALUES ('rollup-close', clock_timestamp(), hi)
    RETURNING id INTO run;

    DELETE FROM rpt.sales_hourly WHERE hour_local >= closing AND hour_local < closing + 1;
    INSERT INTO rpt.sales_hourly (hour_local, category, orders, units, revenue, run_id)
    SELECT date_trunc('hour', o.placed_at AT TIME ZONE tz), p.category,
           count(DISTINCT o.id), sum(l.quantity), sum(l.line_total), run
      FROM src.orders o
      JOIN src.order_lines l ON l.order_id = o.id
      JOIN src.products p ON p.id = l.product_id
     WHERE o.placed_at >= lo AND o.placed_at < hi
     GROUP BY 1, 2;
    GET DIAGNOSTICS n_hours = ROW_COUNT;

    INSERT INTO rpt.sales_daily AS d (day_local, orders, revenue, invoiced_revenue, closed, run_id)
    SELECT closing, count(*), coalesce(sum(o.total), 0),
           coalesce(sum(o.total) FILTER (WHERE o.status = 'invoiced'), 0), true, run
      FROM src.orders o
     WHERE o.placed_at >= lo AND o.placed_at < hi
    ON CONFLICT (day_local) DO UPDATE
       SET orders = excluded.orders, revenue = excluded.revenue,
           invoiced_revenue = excluded.invoiced_revenue, closed = true, run_id = excluded.run_id
    RETURNING d.orders INTO n_read;

    UPDATE rpt.etl_runs
       SET finished_at = clock_timestamp(), rows_read = n_read, rows_written = n_hours + 1
     WHERE id = run;
END
$$;
REVOKE EXECUTE ON PROCEDURE rpt.close_day() FROM PUBLIC;
GRANT EXECUTE ON PROCEDURE rpt.close_day() TO bi_etl;

-- --- Grants (master spec 9.7) ------------------------------------------------

-- The agency's loader writes what it publishes and its ledger; the
-- business settings are the data load's.
GRANT USAGE ON SCHEMA rpt, src TO bi_etl;
GRANT SELECT, INSERT, UPDATE, DELETE ON rpt.sales_hourly, rpt.sales_daily, rpt.etl_runs TO bi_etl;
GRANT SELECT ON rpt.business_settings TO bi_etl;

-- The dashboards read what is published, nothing else.
GRANT USAGE ON SCHEMA rpt TO bi_reader;
GRANT SELECT ON rpt.sales_hourly, rpt.sales_daily, rpt.etl_runs, rpt.business_settings
   TO bi_reader;

RESET ROLE;

-- --- The source, over postgres_fdw (master spec 8.6, 9.6) ----------------------

-- The foreign server is postgres's; the baseline's only user mapping is
-- bi_etl's, to shop_etl, whose password load-data sets from shop_etl's
-- secret. bi_etl has no USAGE on the server: it can neither create a
-- mapping nor change its own.
CREATE SERVER shop_db FOREIGN DATA WRAPPER postgres_fdw
    OPTIONS (host 'db', port '5432', dbname 'shop');
CREATE USER MAPPING FOR bi_etl SERVER shop_db OPTIONS (user 'shop_etl');

-- Each foreign table declares only the columns the close needs; src.orders
-- has no customer_id (nor could shop_etl read it).
CREATE FOREIGN TABLE src.orders (
    id        integer       NOT NULL,
    placed_at timestamptz   NOT NULL,
    status    text          NOT NULL,
    total     numeric(10,2) NOT NULL
) SERVER shop_db OPTIONS (schema_name 'public', table_name 'orders');
CREATE FOREIGN TABLE src.order_lines (
    order_id   integer       NOT NULL,
    product_id integer       NOT NULL,
    quantity   integer       NOT NULL,
    line_total numeric(10,2) NOT NULL
) SERVER shop_db OPTIONS (schema_name 'public', table_name 'order_lines');
CREATE FOREIGN TABLE src.products (
    id       integer NOT NULL,
    category text    NOT NULL
) SERVER shop_db OPTIONS (schema_name 'public', table_name 'products');
GRANT SELECT ON src.orders, src.order_lines, src.products TO bi_etl;

ANALYZE rpt.business_settings;
