def _numbers(field_text):
    return [int(v) for v in str(field_text).split(",")]


def cron_hours(hour):
    """The hours an hour field of the cron subset fires at (v0.4 capture W1
    item 0, spec D219): a comma list of `n`, `a-b`, `*/s` or `a-b/s`."""
    hours = set()
    for item in str(hour).split(","):
        span, _, step = item.partition("/")
        if span == "*":
            lo, hi = 0, 23
        else:
            a, _, b = span.partition("-")
            lo, hi = int(a), int(b or a)
        hours.update(range(lo, hi + 1, int(step or 1)))
    return hours


def shift_cron(at, shift):
    """A cron time in scenario time -> UTC (`jobs.yaml`'s `at`, a seeded
    crontab's entries; v0.4 capture W1 item 0, widening v0.3's item 7):
    the hour field expanded to the hours it fires at, each moved by -shift
    modulo 24, written back as a sorted list (`*` stays `*`); the day of
    week moved with a wrapping hour (allowed only with a single-number
    hour). Minute, day of month and month are unchanged."""
    minute, hour, dom, month, dow = str(at).split()
    if hour == "*":
        return at
    hours = sorted({(h - shift) % 24 for h in cron_hours(hour)})
    if dow != "*":
        carry = (_numbers(hour)[0] - shift) // 24
        dow = ",".join(str(d) for d in sorted({(d + carry) % 7 for d in _numbers(dow)}))
    return " ".join([minute, ",".join(str(h) for h in hours), dom, month, dow])


# A crontab line's five time fields and the rest, each separator kept.
CRONTAB_ENTRY_RE = re.compile(r"^(\s*)(\S+)(\s+)(\S+)(\s+)(\S+)(\s+)(\S+)(\s+)(\S+)(\s.*)$")
CRONTAB_SETTING_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\s*=")


def render_crontab(text, shift):
    """A seeded crontab in scenario time -> UTC (master spec 8.5; v0.4
    capture W1 item 0): each entry's hour field (and its day of week) as
    shift_cron moves them; blank lines, comments, environment settings and
    every other character left as written. The players' file: no header."""
    out = []
    for line in text.splitlines(keepends=True):
        body = line.rstrip("\r\n")
        entry = body.strip()
        m = CRONTAB_ENTRY_RE.match(body)
        if not entry or entry.startswith(("#", "@")) or CRONTAB_SETTING_RE.match(entry) \
                or m is None:
            out.append(line)
            continue
        parts = list(m.groups())
        times = shift_cron(" ".join(parts[1:10:2]), shift).split()
        parts[3], parts[9] = times[1], times[4]
        out.append("".join(parts) + line[len(body):])
    return "".join(out)


def render_jobs(doc, shift):
    """jobs.yaml in UTC: a job's `at` shifted, no `timezone:`; a job with
    `timezone_offset: N` (D168) keeps its `at` as designed and gets the
    fixed zone UTC+M, M = shift + N wrapped into UTC-12..UTC+14."""
    jobs = []
    for job in (doc or {}).get("jobs") or []:
        out = {k: v for k, v in job.items() if k not in ("at", "timezone_offset")}
        if "timezone_offset" in job:
            out["at"] = job["at"]
            out["timezone"] = zone_name(wrap_offset(shift + int(job["timezone_offset"])))
        else:
            out["at"] = shift_cron(job["at"], shift)
        jobs.append(out)
    return {"jobs": jobs}


def _hour_spans(hours):
    """`{"HH" or "HH-HH": multiplier}` -> 24 multipliers, hour 00 first."""
    out = [None] * 24
    for key, value in hours.items():
        lo, _, hi = str(key).partition("-")
        for h in range(int(lo), int(hi or lo) + 1):
            out[h] = value
    return out


def _scenario_week(shape):
    """A scenario shape -> 7 days (Monday first) of 24 multipliers each."""
    if "hours" in shape:
        day = _hour_spans(shape["hours"])
        return [list(day) for _ in WEEKDAYS]
    week = [None] * len(WEEKDAYS)
    for key, value in shape["days"].items():
        lo, _, hi = str(key).partition("-")
        for d in range(WEEKDAYS.index(lo), WEEKDAYS.index(hi or lo) + 1):
            week[d] = _hour_spans(value["hours"])
    return week


def render_shape(shape, shift):
    """A shape in scenario time -> `{utc: {mon..sun: [24 multipliers]}}`:
    UTC hour u of weekday d takes the scenario's multiplier at u + shift,
    on the day before or after when it wraps."""
    week = _scenario_week(shape)
    utc = {}
    for d, day in enumerate(WEEKDAYS):
        hours = []
        for u in range(24):
            total = u + shift
            hours.append(week[(d + total // 24) % 7][total % 24])
        utc[day] = hours
    return {"utc": utc}


def moment_instant(moment, planned, rendered_at):
    """A timeline moment as a UTC instant: `handover-<N>h` N hours before
    the planned hand-over; `T0` as the render time, which no load start
    can precede (a change at or before the start applies at it, W1-y)."""
    m = HANDOVER_MOMENT_RE.match(str(moment))
    if m is None:
        return rendered_at
    return iso(planned - datetime.timedelta(hours=int(m.group(1))))


