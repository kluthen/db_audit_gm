-- vet-machinery's pacs database (v0.5 master spec 9.6; specs/versions/v0.5/
-- vet-machinery-domain.md, "The data model", "Application roles and
-- grants"): the imaging archive and its worklist, one of the three machine
-- systems' databases on the machinery's server (machines by convention).
--
-- The database convention (v0.5 capture W2 item 3; master spec 6.1, the
-- several-database part): gmctl load-data creates pacs, vitals and biomed
-- when absent (owner postgres, CONNECT revoked from PUBLIC) and runs each
-- database's schema.sql then load.sql connected to it, as postgres, in the
-- order domain.yaml's databases lists them, so this file runs first. It never
-- creates a database nor connects to one, and names its database :"DBNAME".
--
-- The part's roles are the instance's: they are created here, once, at top
-- level (capture W3 item 0), and vitals' and biomed's schemas only grant.
-- The login roles' passwords are the game's secrets, set by load-data. The
-- purposes' roles (mach_orders, mach_archive) and the ops schema are purposes
-- 13's and 14's (capture W3 item 0).
--
-- Tables are prefixed mach_ in public; integer keys GENERATED BY DEFAULT AS
-- IDENTITY, written explicitly by the load in the ranges docs/gm.md
-- documents, each sequence set after its range. The core's keys (request,
-- consultation, animal, staff) are plain integer columns with no foreign key;
-- machine_id is biomed's, a plain column here.
CREATE ROLE mach NOLOGIN;            -- owns everything, in each database
CREATE ROLE mach_pacs_app LOGIN;     -- the PACS, its worklist and the modalities (equipment)
CREATE ROLE mach_vitals_app LOGIN;   -- the central station and the monitors (equipment)
CREATE ROLE mach_biomed_app LOGIN;   -- biomedical engineering and the machines' service side
CREATE ROLE mach_maint LOGIN;        -- the partition jobs on machines' pg_cron (data/cron.sql)
CREATE ROLE mach_service LOGIN;      -- the vendors' remote service; no producer in v0.5

-- CONNECT to its own role only (T200: PostgreSQL's default leaves it to
-- PUBLIC, which load-data revokes; this file says so again).
REVOKE CONNECT ON DATABASE :"DBNAME" FROM PUBLIC;
GRANT CONNECT ON DATABASE :"DBNAME" TO mach_pacs_app;

GRANT USAGE, CREATE ON SCHEMA public TO mach;
SET ROLE mach;

-- One row, written by load.sql: the customer's zone and offset (this
-- database's copy; vitals and biomed keep theirs, the databases being
-- separate), the routine turnaround in working hours (D376).
CREATE TABLE mach_pacs_settings (
    timezone         text    NOT NULL,
    utc_offset_hours integer NOT NULL,
    turnaround_hours integer NOT NULL DEFAULT 72,   -- routine: two working days to the study, one to the final
    urgent_hours     integer NOT NULL DEFAULT 18    -- urgent: the next working morning
);
CREATE UNIQUE INDEX mach_pacs_settings_one_row ON mach_pacs_settings ((true));

-- The 30 study codes (vet-machinery-domain.md, "The procedure catalogue",
-- D372, D373): code is the core's requests.code. turnaround_hours counts
-- working hours of the imaging day.
CREATE TABLE mach_procedures (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             text    NOT NULL UNIQUE,
    name             text    NOT NULL,
    modality         text    NOT NULL CHECK (modality IN ('CT', 'MR', 'DX', 'US', 'NM')),
    species_group    text    NOT NULL CHECK (species_group IN ('small', 'large', 'horse', 'any')),
    body_part        text    NOT NULL,
    minutes          integer NOT NULL CHECK (minutes > 0),
    under_ga         boolean NOT NULL,
    turnaround_hours integer NOT NULL
);

-- One entry per imaging request sent (accession I-<request id>, unique: the
-- round trip's idempotency key); the identity is what the lookup API
-- answered, in DICOM's form (patient_name "owner's surname^animal's name",
-- PS3.5 6.2; the owner as Responsible Person, PS3.3 C.7.1.1).
CREATE TABLE mach_worklist (
    id                 integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accession          text        NOT NULL UNIQUE,
    request_id         integer     NOT NULL,
    consultation_id    integer     NOT NULL,
    animal_id          integer     NOT NULL,
    requested_by       integer     NOT NULL,
    procedure_id       integer     NOT NULL REFERENCES mach_procedures,
    priority           text        NOT NULL CHECK (priority IN ('routine', 'urgent')),
    machine_id         integer,
    scheduled_at       timestamptz,
    booking_id         integer,                        -- vet-scheduling's, empty in v0.5
    patient_id         text,                           -- A-<animal id>
    patient_name       text,
    species            text,
    breed              text,
    sex                text,
    born_on            date,
    microchip          text,
    ueln               text,
    ear_tag            text,
    responsible_person text,                           -- the owner's name, role OWNER
    identity_at        timestamptz,
    state              text        NOT NULL DEFAULT 'new'
                       CHECK (state IN ('new', 'scheduled', 'in-progress', 'completed', 'cancelled')),
    cancelled_because  text,
    cancelled_at       timestamptz,
    created_at         timestamptz NOT NULL,
    CHECK ((state = 'cancelled') = (cancelled_at IS NOT NULL)),
    CHECK (state = 'new' OR state = 'cancelled' OR identity_at IS NOT NULL)
);
CREATE INDEX mach_worklist_state_idx ON mach_worklist (state, created_at);
CREATE INDEX mach_worklist_machine_idx ON mach_worklist (machine_id, state, scheduled_at);
CREATE INDEX mach_worklist_request_idx ON mach_worklist (request_id);

-- A study, as acquired on the modality: from its entry, or unscheduled (a
-- night's urgent study typed on the modality, worklist_id empty until it is
-- reconciled). The radiation record of an ionising study (rule 5).
CREATE TABLE mach_studies (
    id                integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_uid         text          NOT NULL UNIQUE,
    worklist_id       integer       REFERENCES mach_worklist,
    accession         text,                            -- as acquired; none when typed
    machine_id        integer       NOT NULL,
    patient_id        text          NOT NULL,          -- as acquired
    patient_name      text          NOT NULL,
    performed_by      integer       NOT NULL,          -- a radiographer, staff 52-55
    restrained_by     integer,                         -- ionising studies
    companion_present boolean       NOT NULL DEFAULT false,
    started_at        timestamptz   NOT NULL,
    ended_at          timestamptz,
    images            integer       NOT NULL DEFAULT 0,
    size_mb           numeric(10,1) NOT NULL DEFAULT 0,
    exposure          text,                            -- kV and mAs; CT's DLP; NM's activity; none for MR, US
    state             text          NOT NULL DEFAULT 'acquired'
                      CHECK (state IN ('acquired', 'reconciled', 'reported', 'unmatched')),
    reconciled_at     timestamptz,
    reconciled_by     integer
);
CREATE INDEX mach_studies_worklist_idx ON mach_studies (worklist_id);
CREATE INDEX mach_studies_state_idx ON mach_studies (state, started_at);

CREATE TABLE mach_series (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_id    integer NOT NULL REFERENCES mach_studies,
    number      integer NOT NULL,
    modality    text    NOT NULL,
    body_part   text    NOT NULL,
    description text    NOT NULL,
    images      integer NOT NULL,
    UNIQUE (study_id, number)
);

-- A report: the duty vet's preliminary (urgent studies, signed at once), the
-- imaging specialist's final; an addendum is a new final superseding the
-- signed one, which is kept (rule 2).
CREATE TABLE mach_reports (
    id            integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_id      integer     NOT NULL REFERENCES mach_studies,
    kind          text        NOT NULL CHECK (kind IN ('preliminary', 'final')),
    author        integer     NOT NULL,
    findings      text        NOT NULL,
    conclusion    text        NOT NULL,
    status        text        NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'signed')),
    signed_at     timestamptz,
    supersedes_id integer     REFERENCES mach_reports,
    why           text,
    CHECK ((status = 'signed') = (signed_at IS NOT NULL)),
    CHECK ((supersedes_id IS NULL) = (why IS NULL))
);
CREATE INDEX mach_reports_study_idx ON mach_reports (study_id);
CREATE INDEX mach_reports_signed_idx ON mach_reports (kind, signed_at);

RESET ROLE;
REVOKE CREATE ON SCHEMA public FROM mach;

-- --- Grants (vet-machinery-domain.md, "Application roles and grants") --------

-- The PACS and the modalities read every table and write the entries'
-- scheduling, identity and state, the studies, series and reports; never the
-- procedures. The entries themselves are purpose 13's (mach_orders).
GRANT SELECT ON ALL TABLES IN SCHEMA public TO mach_pacs_app;
GRANT UPDATE (machine_id, scheduled_at, booking_id, patient_id, patient_name, species, breed, sex,
              born_on, microchip, ueln, ear_tag, responsible_person, identity_at, state,
              cancelled_because, cancelled_at)
   ON mach_worklist TO mach_pacs_app;
GRANT INSERT, UPDATE ON mach_studies, mach_series, mach_reports TO mach_pacs_app;
