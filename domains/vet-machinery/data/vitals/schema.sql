-- vet-machinery's vitals database (v0.5 master spec 9.6; specs/versions/v0.5/
-- vet-machinery-domain.md, "The data model"): the monitors' central station,
-- on the machinery's server beside pacs and biomed. Run by load-data after
-- pacs' files, connected to this database, as postgres: the part's roles
-- exist (pacs/schema.sql creates them, capture W3 item 0), so this file only
-- grants. It never creates a database nor connects to one.
--
-- mach_vitals, the 10-second rows, is partitioned by the customer's local
-- day on at (capture W3 item 4): mach_vitals_<yyyymmdd> for [d 00:00,
-- d+1 00:00) at the settings' fixed offset, beside mach_vitals_default,
-- empty by design. Its indexes are on the parent, so every partition gets
-- them. mach_create_partitions(days) creates them ahead (the pg_cron job
-- vitals-partitions, as mach_maint); mach_drop_shipped(day) detaches and
-- drops a shipped day (purpose 14, as mach_archive): both SECURITY DEFINER,
-- owned by mach, with a fixed search_path (T237), so the jobs never own the
-- table. mach keeps CREATE on public for them.
REVOKE CONNECT ON DATABASE :"DBNAME" FROM PUBLIC;
GRANT CONNECT ON DATABASE :"DBNAME" TO mach_vitals_app, mach_maint;

GRANT USAGE, CREATE ON SCHEMA public TO mach;
SET ROLE mach;

-- One row, written by load.sql: the customer's zone and offset (this
-- database's copy, the partitions' day boundary), the on-site window in full
-- days, the chart's intervals.
CREATE TABLE mach_vitals_settings (
    timezone             text    NOT NULL,
    utc_offset_hours     integer NOT NULL,
    window_days          integer NOT NULL DEFAULT 1,    -- today and the last full day (D288)
    chart_anaesthesia_min integer NOT NULL DEFAULT 5,
    chart_icu_min        integer NOT NULL DEFAULT 60
);
CREATE UNIQUE INDEX mach_vitals_settings_one_row ON mach_vitals_settings ((true));

-- The core's current stays as the lookup API last answered (mach.census,
-- every five minutes): a stay no longer current is marked left.
CREATE TABLE mach_census (
    stay_id     integer     PRIMARY KEY,
    animal_id   integer     NOT NULL,
    animal_name text        NOT NULL,
    species     text        NOT NULL,
    section_id  integer     NOT NULL,
    admitted_at timestamptz NOT NULL,
    seen_at     timestamptz NOT NULL,
    left_at     timestamptz
);
CREATE INDEX mach_census_current_idx ON mach_census (left_at, section_id);

-- A monitor session on a stay: intensive care (monitors 21-28) or
-- anaesthesia (17-20); ended by the census when the stay leaves, or by staff
-- (the step-down, the end of anaesthesia).
CREATE TABLE mach_sessions (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id  integer      NOT NULL,
    kind        text         NOT NULL CHECK (kind IN ('anaesthesia', 'icu')),
    stay_id     integer      NOT NULL,
    animal_id   integer      NOT NULL,
    animal_name text         NOT NULL,
    species     text         NOT NULL,
    weight_kg   numeric(6,1) NOT NULL,
    started_at  timestamptz  NOT NULL,
    started_by  integer      NOT NULL,
    ended_at    timestamptz,
    ended_by    text         CHECK (ended_by IN ('census', 'staff')),
    CHECK ((ended_at IS NULL) = (ended_by IS NULL)),
    CHECK (ended_at IS NULL OR ended_at > started_at)
);
CREATE INDEX mach_sessions_open_idx ON mach_sessions (machine_id) WHERE ended_at IS NULL;
CREATE INDEX mach_sessions_stay_idx ON mach_sessions (stay_id);
CREATE INDEX mach_sessions_started_idx ON mach_sessions (started_at);

-- The raw vitals, a row every 10 seconds per open session on the UTC
-- minute's grid; shipped to the vault after the window (purpose 14), by the
-- session's id only (rule 10).
CREATE TABLE mach_vitals (
    session_id  integer      NOT NULL,
    at          timestamptz  NOT NULL,
    heart_rate  integer,
    resp_rate   integer,
    spo2        integer,
    etco2       integer,
    systolic    integer,
    diastolic   integer,
    mean_bp     integer,
    temperature numeric(4,1),
    PRIMARY KEY (session_id, at)
) PARTITION BY RANGE (at);
CREATE TABLE mach_vitals_default PARTITION OF mach_vitals DEFAULT;

-- The chart, the clinical record kept five years (rule 8): every 5 minutes
-- under anaesthesia, hourly in intensive care, each measure's mean, min and
-- max over the interval ending at `at`.
CREATE TABLE mach_vitals_chart (
    session_id      integer      NOT NULL REFERENCES mach_sessions,
    at              timestamptz  NOT NULL,
    heart_rate      integer,
    heart_rate_min  integer,
    heart_rate_max  integer,
    resp_rate       integer,
    resp_rate_min   integer,
    resp_rate_max   integer,
    spo2            integer,
    spo2_min        integer,
    spo2_max        integer,
    etco2           integer,
    etco2_min       integer,
    etco2_max       integer,
    systolic        integer,
    systolic_min    integer,
    systolic_max    integer,
    diastolic       integer,
    diastolic_min   integer,
    diastolic_max   integer,
    mean_bp         integer,
    mean_bp_min     integer,
    mean_bp_max     integer,
    temperature     numeric(4,1),
    temperature_min numeric(4,1),
    temperature_max numeric(4,1),
    PRIMARY KEY (session_id, at)
);

CREATE TABLE mach_alarms (
    id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id      integer     NOT NULL REFERENCES mach_sessions,
    at              timestamptz NOT NULL,
    priority        text        NOT NULL CHECK (priority IN ('high', 'medium', 'low')),
    kind            text        NOT NULL CHECK (kind IN ('physiological', 'technical')),
    parameter       text        NOT NULL,
    value           text,
    acknowledged_at timestamptz,
    acknowledged_by integer
);
CREATE INDEX mach_alarms_open_idx ON mach_alarms (at) WHERE acknowledged_at IS NULL;
CREATE INDEX mach_alarms_session_idx ON mach_alarms (session_id);

-- --- The partitions (capture W3 item 4) --------------------------------------

-- Day d's partition of mach_vitals, [d 00:00, d+1 00:00) local; false when it
-- exists. Called by the two functions below and by load.sql (as mach).
CREATE FUNCTION mach_partition_day(d date) RETURNS boolean
    LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE
    o integer := (SELECT utc_offset_hours FROM mach_vitals_settings);
    part text := 'mach_vitals_' || to_char(d, 'YYYYMMDD');
BEGIN
    IF o IS NULL THEN
        RAISE EXCEPTION 'mach_partition_day: mach_vitals_settings holds no offset';
    END IF;
    IF to_regclass(part) IS NOT NULL THEN
        RETURN false;
    END IF;
    EXECUTE format('CREATE TABLE %I PARTITION OF mach_vitals FOR VALUES FROM (%L) TO (%L)', part,
                   (d::timestamp - make_interval(hours => o)) AT TIME ZONE 'UTC',
                   ((d + 1)::timestamp - make_interval(hours => o)) AT TIME ZONE 'UTC');
    RETURN true;
END $$;

-- The partitions from today (local) to today plus `days`: how many it created.
CREATE FUNCTION mach_create_partitions(days integer) RETURNS integer
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    today date := ((now() AT TIME ZONE 'UTC')
                   + make_interval(hours => (SELECT utc_offset_hours FROM mach_vitals_settings)))::date;
    made integer := 0;
BEGIN
    FOR i IN 0 .. greatest(days, 0) LOOP
        IF mach_partition_day(today + i) THEN
            made := made + 1;
        END IF;
    END LOOP;
    RETURN made;
END $$;

-- A shipped day's partition detached and dropped (never deleted from, cold
-- storage 2); false when there is none.
CREATE FUNCTION mach_drop_shipped(day date) RETURNS boolean
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    part text := 'mach_vitals_' || to_char(day, 'YYYYMMDD');
BEGIN
    IF to_regclass(part) IS NULL THEN
        RETURN false;
    END IF;
    EXECUTE format('ALTER TABLE mach_vitals DETACH PARTITION %I', part);
    EXECUTE format('DROP TABLE %I', part);
    RETURN true;
END $$;

RESET ROLE;
-- mach keeps CREATE on public: the partition functions create the days ahead.

REVOKE EXECUTE ON FUNCTION mach_partition_day(date), mach_create_partitions(integer),
                           mach_drop_shipped(date) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION mach_create_partitions(integer) TO mach_maint;

-- --- Grants (vet-machinery-domain.md, "Application roles and grants") --------

-- The central station and the monitors read every table and write the
-- census, sessions, vitals, chart and alarms. mach_drop_shipped is purpose
-- 14's (mach_archive).
GRANT SELECT ON ALL TABLES IN SCHEMA public TO mach_vitals_app;
GRANT INSERT, UPDATE ON mach_census, mach_sessions, mach_vitals, mach_vitals_chart, mach_alarms
   TO mach_vitals_app;
