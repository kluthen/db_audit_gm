-- vet-machinery's biomed database (v0.5 master spec 9.6; specs/versions/v0.5/
-- vet-machinery-domain.md, "The data model"): the biomedical engineering
-- system, its registry of the 28 machines (the ids vet-lab and
-- vet-scheduling use), maintenance and QA, downtimes, the machines' logs and
-- their telemetry. Run by load-data after vitals' files, connected to this
-- database, as postgres; the part's roles exist (pacs/schema.sql), so this
-- file only grants. It never creates a database nor connects to one.
--
-- mach_readings is partitioned by the customer's local day on read_at,
-- mach_readings_<yyyymmdd>, shipped after the window (purpose 14); mach_events
-- by local month on at, mach_events_<yyyymm>, kept twelve months (rule 4);
-- each beside its _default partition, empty by design, its indexes on the
-- parent (capture W3 item 4). mach_create_partitions(days) creates the
-- readings' days from today to today plus `days` and the events' months
-- those days touch (the pg_cron jobs readings-partitions daily and
-- events-partitions on the 25th, as mach_maint); mach_drop_shipped(day)
-- detaches and drops a shipped readings day (purpose 14): SECURITY DEFINER,
-- owned by mach, a fixed search_path (T237). mach keeps CREATE on public.
REVOKE CONNECT ON DATABASE :"DBNAME" FROM PUBLIC;
GRANT CONNECT ON DATABASE :"DBNAME" TO mach_biomed_app, mach_maint, mach_service;

GRANT USAGE, CREATE ON SCHEMA public TO mach;
SET ROLE mach;

-- One row, written by load.sql: the customer's zone and offset (the
-- partitions' day and month boundaries), the on-site window (one full day),
-- the logs' retention (twelve months, rule 4).
CREATE TABLE mach_settings (
    timezone                text    NOT NULL,
    utc_offset_hours        integer NOT NULL,
    window_days             integer NOT NULL DEFAULT 1,
    events_retention_months integer NOT NULL DEFAULT 12
);
CREATE UNIQUE INDEX mach_settings_one_row ON mach_settings ((true));

-- The registry (vet-machinery-domain.md, "Deterministic key ranges"): 1-6 the
-- lab's analysers, 7-16 imaging (bookable), 17-20 anaesthesia monitors,
-- 21-28 intensive-care monitors. section_id is the core's.
CREATE TABLE mach_machines (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          text    NOT NULL UNIQUE,
    name          text    NOT NULL,
    kind          text    NOT NULL CHECK (kind IN ('analyser', 'ct', 'mri', 'dr', 'us', 'gamma',
                                                   'monitor-anaesthesia', 'monitor-icu')),
    modality      text    CHECK (modality IN ('CT', 'MR', 'DX', 'US', 'NM')),
    ae_title      text    UNIQUE,                     -- the modality's DICOM name
    section_id    integer,
    discipline    text,                               -- analysers
    species_group text    NOT NULL CHECK (species_group IN ('small', 'large', 'horse', 'any')),
    vendor        text    NOT NULL,
    model         text    NOT NULL,
    serial        text    NOT NULL UNIQUE,
    installed_on  date    NOT NULL,
    bookable      boolean NOT NULL DEFAULT false,
    ionising      boolean NOT NULL DEFAULT false,
    telemetry     boolean NOT NULL DEFAULT false,
    status        text    NOT NULL DEFAULT 'in-service' CHECK (status IN ('in-service', 'down', 'retired')),
    qa_due_on     date,                               -- ionising machines (rule 6)
    CHECK (ionising = (qa_due_on IS NOT NULL))
);

CREATE TABLE mach_maintenance (
    id           integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id   integer     NOT NULL REFERENCES mach_machines,
    kind         text        NOT NULL CHECK (kind IN ('service', 'repair', 'qa-test', 'calibration',
                                                      'software-update')),
    performed_at timestamptz NOT NULL,
    vendor       text,
    engineer     text,                                -- the vendor engineer's name (personal)
    staff_id     integer,                             -- or the biomedical engineer
    outcome      text        NOT NULL CHECK (outcome IN ('pass', 'fail', 'done')),
    next_due_on  date,
    notes        text,
    CHECK (engineer IS NOT NULL OR staff_id IS NOT NULL)
);
CREATE INDEX mach_maintenance_machine_idx ON mach_maintenance (machine_id, performed_at);

CREATE TABLE mach_downtimes (
    id         integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id integer     NOT NULL REFERENCES mach_machines,
    from_at    timestamptz NOT NULL,
    until_at   timestamptz,                           -- open while down
    reason     text        NOT NULL,
    CHECK (until_at IS NULL OR until_at > from_at)
);
CREATE INDEX mach_downtimes_machine_idx ON mach_downtimes (machine_id, from_at);

-- The machines' logs: an operator by staff id only, never a name (rule 4);
-- critical events acknowledged by the biomedical engineer (rule 7).
CREATE TABLE mach_events (
    id              integer     GENERATED BY DEFAULT AS IDENTITY,
    machine_id      integer     NOT NULL REFERENCES mach_machines,
    at              timestamptz NOT NULL,
    level           text        NOT NULL CHECK (level IN ('info', 'warning', 'error', 'critical')),
    code            text        NOT NULL,
    message         text        NOT NULL,
    operator_id     integer,
    acknowledged_at timestamptz,
    acknowledged_by integer,
    PRIMARY KEY (id, at)
) PARTITION BY RANGE (at);
CREATE TABLE mach_events_default PARTITION OF mach_events DEFAULT;
CREATE INDEX mach_events_machine_idx ON mach_events (machine_id, at);
CREATE INDEX mach_events_unacknowledged_idx ON mach_events (at)
    WHERE level = 'critical' AND acknowledged_at IS NULL;

-- A reading a minute per machine with telemetry, its kind's channels.
CREATE TABLE mach_readings (
    machine_id integer     NOT NULL REFERENCES mach_machines,
    read_at    timestamptz NOT NULL,
    status     text        NOT NULL CHECK (status IN ('ok', 'warning', 'fault', 'down')),
    channels   jsonb       NOT NULL,
    PRIMARY KEY (machine_id, read_at)
) PARTITION BY RANGE (read_at);
CREATE TABLE mach_readings_default PARTITION OF mach_readings DEFAULT;

-- The kept aggregate of a readings day (rule 11): its raw rows and each
-- channel's min, max and mean, computed before the day ships.
CREATE TABLE mach_readings_daily (
    machine_id integer NOT NULL REFERENCES mach_machines,
    day        date    NOT NULL,
    rows       integer NOT NULL,
    channels   jsonb   NOT NULL,
    PRIMARY KEY (machine_id, day)
);

-- --- The partitions (capture W3 item 4) --------------------------------------

-- Day d's partition of mach_readings, [d 00:00, d+1 00:00) local; false when
-- it exists.
CREATE FUNCTION mach_partition_day(d date) RETURNS boolean
    LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE
    o integer := (SELECT utc_offset_hours FROM mach_settings);
    part text := 'mach_readings_' || to_char(d, 'YYYYMMDD');
BEGIN
    IF o IS NULL THEN
        RAISE EXCEPTION 'mach_partition_day: mach_settings holds no offset';
    END IF;
    IF to_regclass(part) IS NOT NULL THEN
        RETURN false;
    END IF;
    EXECUTE format('CREATE TABLE %I PARTITION OF mach_readings FOR VALUES FROM (%L) TO (%L)', part,
                   (d::timestamp - make_interval(hours => o)) AT TIME ZONE 'UTC',
                   ((d + 1)::timestamp - make_interval(hours => o)) AT TIME ZONE 'UTC');
    RETURN true;
END $$;

-- The month holding day d's partition of mach_events, local; false when it
-- exists.
CREATE FUNCTION mach_partition_month(d date) RETURNS boolean
    LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE
    o integer := (SELECT utc_offset_hours FROM mach_settings);
    m date := date_trunc('month', d)::date;
    part text := 'mach_events_' || to_char(d, 'YYYYMM');
BEGIN
    IF o IS NULL THEN
        RAISE EXCEPTION 'mach_partition_month: mach_settings holds no offset';
    END IF;
    IF to_regclass(part) IS NOT NULL THEN
        RETURN false;
    END IF;
    EXECUTE format('CREATE TABLE %I PARTITION OF mach_events FOR VALUES FROM (%L) TO (%L)', part,
                   (m::timestamp - make_interval(hours => o)) AT TIME ZONE 'UTC',
                   ((m + interval '1 month')::timestamp - make_interval(hours => o)) AT TIME ZONE 'UTC');
    RETURN true;
END $$;

-- The readings' partitions from today (local) to today plus `days`, and the
-- events' months those days touch: how many it created. The 25th's job asks
-- seven days ahead, which reaches next month in every month.
CREATE FUNCTION mach_create_partitions(days integer) RETURNS integer
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    today date := ((now() AT TIME ZONE 'UTC')
                   + make_interval(hours => (SELECT utc_offset_hours FROM mach_settings)))::date;
    made integer := 0;
BEGIN
    FOR i IN 0 .. greatest(days, 0) LOOP
        IF mach_partition_day(today + i) THEN
            made := made + 1;
        END IF;
        IF mach_partition_month(today + i) THEN
            made := made + 1;
        END IF;
    END LOOP;
    RETURN made;
END $$;

-- A shipped readings day's partition detached and dropped; false when none.
CREATE FUNCTION mach_drop_shipped(day date) RETURNS boolean
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    part text := 'mach_readings_' || to_char(day, 'YYYYMMDD');
BEGIN
    IF to_regclass(part) IS NULL THEN
        RETURN false;
    END IF;
    EXECUTE format('ALTER TABLE mach_readings DETACH PARTITION %I', part);
    EXECUTE format('DROP TABLE %I', part);
    RETURN true;
END $$;

RESET ROLE;
-- mach keeps CREATE on public: the partition functions create the days ahead.

REVOKE EXECUTE ON FUNCTION mach_partition_day(date), mach_partition_month(date),
                           mach_create_partitions(integer), mach_drop_shipped(date) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION mach_create_partitions(integer) TO mach_maint;

-- --- Grants (vet-machinery-domain.md, "Application roles and grants") --------

-- Biomedical engineering and the machines' service side read every table and
-- write events, readings, maintenance and downtimes, and of the registry the
-- machines' status and QA due date only.
GRANT SELECT ON ALL TABLES IN SCHEMA public TO mach_biomed_app;
GRANT INSERT, UPDATE ON mach_events, mach_readings, mach_maintenance, mach_downtimes TO mach_biomed_app;
GRANT UPDATE (status, qa_due_on) ON mach_machines TO mach_biomed_app;

-- The vendors' remote service (rule 9): biomed only, never as a superuser;
-- reads the machines, events, readings and maintenance, records its visits.
GRANT SELECT ON mach_machines, mach_events, mach_readings, mach_maintenance TO mach_service;
GRANT INSERT ON mach_maintenance TO mach_service;
