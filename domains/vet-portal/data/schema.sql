-- --- Releases ----------------------------------------------------------------------------

-- What passed its gate (rule 2): a signed consultation (C-<id>), a released
-- centre test (T-<lab order test id>), an ended stay (S-<id>); record_at the
-- record's own time (the consultation's start, the sample's collection, the
-- admission), gated_at the gate's (signed, released, discharged); an
-- amendment a new version, the former superseded (lab rule 3). body: the
-- diagnoses' labels and the prescriptions, or the analytes with their values,
-- flags and intervals and the performing lab, or the stay's dates and
-- outcome; never free text (rule 3).
CREATE TABLE portal_documents (
    id            integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id     integer,
    herd_id       integer,
    kind          text        NOT NULL CHECK (kind IN ('consultation', 'result', 'discharge')),
    source_ref    text        NOT NULL,
    version       integer     NOT NULL DEFAULT 1,
    record_at     timestamptz NOT NULL,
    gated_at      timestamptz NOT NULL,
    published_at  timestamptz NOT NULL,
    title         text        NOT NULL,
    vet_name      text,
    body          jsonb       NOT NULL,
    supersedes_id integer     REFERENCES portal_documents,
    superseded_at timestamptz,
    UNIQUE (source_ref, version),
    CHECK ((animal_id IS NULL) <> (herd_id IS NULL)),
    CHECK ((version = 1) = (supersedes_id IS NULL))
);
-- An animal's documents, newest first (T294).
CREATE INDEX portal_documents_animal_idx ON portal_documents (animal_id, record_at DESC);
CREATE INDEX portal_documents_herd_idx ON portal_documents (herd_id, record_at DESC) WHERE herd_id IS NOT NULL;

-- Each document opened: with the notices, what was released to whom (rule 8).
CREATE TABLE portal_views (
    id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  integer     NOT NULL REFERENCES portal_accounts,
    document_id integer     NOT NULL REFERENCES portal_documents,
    at          timestamptz NOT NULL,
    action      text        NOT NULL DEFAULT 'open' CHECK (action IN ('open', 'download'))
);
CREATE INDEX portal_views_document_idx ON portal_views (document_id);

-- --- Consents and messages ---------------------------------------------------------------

