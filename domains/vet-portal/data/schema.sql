-- The keeper's clause (W3-e): the animal's current owner's latest
-- keeper-access event for this keeper and animal is a grant. Read as portal,
-- since the owner's ownership row and events are hidden from a keeper by the
-- own-rows policies; the keeping's own end is the animals' policy's (T274
-- bites in either: the withdrawal here, the keeping's end there).
CREATE FUNCTION portal_keeper_granted(p_animal_id integer, p_keeper_id integer) RETURNS boolean
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
SELECT coalesce((SELECT e.granted
                   FROM portal_ownerships o
                   JOIN portal_consent_events e
                     ON e.owner_id = o.owner_id AND e.purpose = 'keeper-access'
                    AND e.animal_id = o.animal_id AND e.keeper_id = p_keeper_id
                  WHERE o.animal_id = p_animal_id AND o.role = 'owner' AND o.until_at IS NULL
                  ORDER BY e.at DESC, e.id DESC
                  LIMIT 1), false)
$$;

-- The current owner's ownership start (since-ownership, T271): a buyer never
-- sees the record from before the sale; a keeper reads the owner's start.
CREATE FUNCTION portal_owner_since(p_animal_id integer) RETURNS timestamptz
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
SELECT o.from_at FROM portal_ownerships o
 WHERE o.animal_id = p_animal_id AND o.role = 'owner' AND o.until_at IS NULL
$$;

CREATE POLICY portal_settings_scope ON portal_settings FOR SELECT TO portal_api USING (true);

-- The asker's own row; the hashes left out by the column grant below.
CREATE POLICY portal_accounts_scope ON portal_accounts FOR ALL TO portal_api
    USING (owner_id = NULLIF(current_setting('portal.owner_id', true), '')::integer);

-- current-owner, or current-keeper-granted (access model 9.3).
CREATE POLICY portal_animals_scope ON portal_animals FOR SELECT TO portal_api
    USING (EXISTS (SELECT 1 FROM portal_ownerships o
                    WHERE o.animal_id = portal_animals.animal_id AND o.role = 'owner'
                      AND o.until_at IS NULL
                      AND o.owner_id = NULLIF(current_setting('portal.owner_id', true), '')::integer)
           OR EXISTS (SELECT 1 FROM portal_ownerships k
                       WHERE k.animal_id = portal_animals.animal_id AND k.role = 'keeper'
                         AND k.until_at IS NULL
                         AND k.owner_id = NULLIF(current_setting('portal.owner_id', true), '')::integer
                         AND portal_keeper_granted(k.animal_id, k.owner_id)));

CREATE POLICY portal_ownerships_scope ON portal_ownerships FOR SELECT TO portal_api
    USING (owner_id = NULLIF(current_setting('portal.owner_id', true), '')::integer);

CREATE POLICY portal_herds_scope ON portal_herds FOR SELECT TO portal_api
    USING (keeper_owner_id = NULLIF(current_setting('portal.owner_id', true), '')::integer);

-- The animal visible as above (read through portal_animals and its policy)
-- and the record within the current ownership (since-ownership); a herd's
-- documents to its keeper.
CREATE POLICY portal_documents_scope ON portal_documents FOR SELECT TO portal_api
    USING ((animal_id IS NOT NULL
            AND EXISTS (SELECT 1 FROM portal_animals a WHERE a.animal_id = portal_documents.animal_id)
            AND record_at >= portal_owner_since(animal_id))
           OR (herd_id IS NOT NULL
               AND EXISTS (SELECT 1 FROM portal_herds h WHERE h.herd_id = portal_documents.herd_id)));

-- The asker's own events; an insert only as the asker, a keeper-access event
-- only for an animal the asker owns now (access model 9.3).
CREATE POLICY portal_consent_events_scope ON portal_consent_events FOR ALL TO portal_api
    USING (owner_id = NULLIF(current_setting('portal.owner_id', true), '')::integer)
    WITH CHECK (owner_id = NULLIF(current_setting('portal.owner_id', true), '')::integer
                AND (purpose = 'reminders'
                     OR EXISTS (SELECT 1 FROM portal_ownerships o
                                 WHERE o.animal_id = portal_consent_events.animal_id
                                   AND o.owner_id = portal_consent_events.owner_id
                                   AND o.role = 'owner' AND o.until_at IS NULL)));

-- Insert only, as the asker's account, of a document the asker sees.
CREATE POLICY portal_views_scope ON portal_views FOR INSERT TO portal_api
    WITH CHECK (EXISTS (SELECT 1 FROM portal_accounts a
                         WHERE a.id = portal_views.account_id
                           AND a.owner_id = NULLIF(current_setting('portal.owner_id', true), '')::integer)
                AND EXISTS (SELECT 1 FROM portal_documents d WHERE d.id = portal_views.document_id));

-- The sessions' purge: sessions ended (or expired) 30 days ago (rule 11).
CREATE POLICY portal_sessions_purge ON portal_sessions FOR ALL TO portal_housekeeping
    USING (coalesce(ended_at, expires_at) < now() - interval '30 days');

-- --- The functions before anyone is known (the API's db/ side, D271) ----------------------

-- A one-time link's token and a session's: random, kept only as SHA-256.
CREATE FUNCTION portal_token_hash(p_token text) RETURNS text
  LANGUAGE sql IMMUTABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
SELECT encode(digest(p_token, 'sha256'), 'hex')
$$;

-- An outbox row for an account message (invitation, reset, closure), by
-- e-mail; its key random (a message made in play).
CREATE FUNCTION portal_queue_account_message(p_account portal_accounts, p_template text, p_link text)
  RETURNS void
  LANGUAGE sql VOLATILE SECURITY DEFINER SET search_path = public, pg_temp AS $$
INSERT INTO portal_outbox (message_key, account_id, owner_id, template, channel, address, payload,
                           queued_at)
VALUES (gen_random_uuid(), p_account.id, p_account.owner_id, p_template, 'email', p_account.email,
        jsonb_build_object('template', p_template, 'name', p_account.display_name, 'link', p_link),
        now())
$$;

-- portal_login(email, password): result 'ok' with a new session's token,
-- 'wrong' (401: no such active account, a wrong password), 'locked' (423:
-- five failures lock for 30 minutes). A success resets the failures (T279).
CREATE FUNCTION portal_login(p_email text, p_password text, OUT result text, OUT token text)
  LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    a portal_accounts;
    s portal_settings;
BEGIN
    SELECT * INTO s FROM portal_settings LIMIT 1;
    SELECT * INTO a FROM portal_accounts
     WHERE lower(email) = lower(p_email) AND status = 'active' FOR UPDATE;
    IF NOT FOUND THEN
        result := 'wrong';
        RETURN;
    END IF;
    IF a.locked_until > now() THEN
        result := 'locked';
        RETURN;
    END IF;
    IF a.password_hash IS NULL OR crypt(p_password, a.password_hash) <> a.password_hash THEN
        IF a.failed_logins + 1 >= s.lock_failures THEN
            UPDATE portal_accounts SET failed_logins = 0,
                   locked_until = now() + s.lock_minutes * interval '1 minute'
             WHERE id = a.id;
            result := 'locked';
        ELSE
            UPDATE portal_accounts SET failed_logins = failed_logins + 1 WHERE id = a.id;
            result := 'wrong';
        END IF;
        RETURN;
    END IF;
    token := encode(gen_random_bytes(32), 'hex');
    INSERT INTO portal_sessions (account_id, token_hash, created_at, last_seen_at, expires_at)
    VALUES (a.id, portal_token_hash(token), now(), now(), now() + s.session_hours * interval '1 hour');
    UPDATE portal_accounts SET failed_logins = 0, locked_until = NULL, last_login_at = now()
     WHERE id = a.id;
    result := 'ok';
END
$$;

-- portal_session(token): the account and its owner while the session is
-- open, seen within the idle limit and under its longest life (T276); a
-- session found idle or expired is ended as such, and yields no account.
CREATE FUNCTION portal_session(p_token text, OUT account_id integer, OUT owner_id integer)
  LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    ss portal_sessions;
    s portal_settings;
BEGIN
    SELECT * INTO s FROM portal_settings LIMIT 1;
    SELECT * INTO ss FROM portal_sessions
     WHERE token_hash = portal_token_hash(p_token) AND ended_at IS NULL FOR UPDATE;
    IF NOT FOUND THEN
        RETURN;
    END IF;
    IF ss.expires_at <= now() THEN
        UPDATE portal_sessions SET ended_at = ss.expires_at, ended_by = 'expiry' WHERE id = ss.id;
        RETURN;
    END IF;
    IF ss.last_seen_at + s.idle_minutes * interval '1 minute' <= now() THEN
        UPDATE portal_sessions SET ended_at = ss.last_seen_at + s.idle_minutes * interval '1 minute',
               ended_by = 'idle' WHERE id = ss.id;
        RETURN;
    END IF;
    SELECT a.id, a.owner_id INTO account_id, owner_id FROM portal_accounts a
     WHERE a.id = ss.account_id AND a.status = 'active';
    IF FOUND THEN
        UPDATE portal_sessions SET last_seen_at = now() WHERE id = ss.id;
    END IF;
END
$$;

-- portal_logout(token): the session ended (POST /logout; W3-e: the sessions
-- have no grant, so the logout is a function too).
CREATE FUNCTION portal_logout(p_token text) RETURNS boolean
  LANGUAGE sql VOLATILE SECURITY DEFINER SET search_path = public, pg_temp AS $$
WITH e AS (UPDATE portal_sessions SET ended_at = now(), ended_by = 'logout'
            WHERE token_hash = portal_token_hash(p_token) AND ended_at IS NULL RETURNING 1)
SELECT EXISTS (SELECT 1 FROM e)
$$;

-- portal_activate(token, password, reminders): an invited account's
-- unexpired invitation used once (T282): the password set (bcrypt, cost 6,
-- T278), active, the reminders' consent offered (an activation event when
-- granted). The account's id, or null (401).
CREATE FUNCTION portal_activate(p_token text, p_password text, p_reminders boolean) RETURNS integer
  LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    a portal_accounts;
BEGIN
    SELECT * INTO a FROM portal_accounts
     WHERE invite_hash = portal_token_hash(p_token) AND invite_expires_at > now()
       AND status = 'invited' FOR UPDATE;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;
    UPDATE portal_accounts SET status = 'active', activated_at = now(),
           password_hash = crypt(p_password, gen_salt('bf', 6)),
           invite_hash = NULL, invite_expires_at = NULL, failed_logins = 0, locked_until = NULL,
           reminders = coalesce(p_reminders, false)
     WHERE id = a.id;
    IF p_reminders THEN
        INSERT INTO portal_consent_events (owner_id, purpose, granted, at, source)
        VALUES (a.owner_id, 'reminders', true, now(), 'activation');
    END IF;
    RETURN a.id;
END
$$;

-- portal_request_reset(email): a password-reset message to the account's own
-- e-mail with a new one-time link (own-email); nothing for an unknown address
-- or a closed account, answered the same.
CREATE FUNCTION portal_request_reset(p_email text) RETURNS void
  LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    a portal_accounts;
    s portal_settings;
    t text;
BEGIN
    SELECT * INTO s FROM portal_settings LIMIT 1;
    SELECT * INTO a FROM portal_accounts
     WHERE lower(email) = lower(p_email) AND status IN ('invited', 'active') FOR UPDATE;
    IF NOT FOUND THEN
        RETURN;
    END IF;
    t := encode(gen_random_bytes(32), 'hex');
    UPDATE portal_accounts SET invite_hash = portal_token_hash(t),
           invite_expires_at = now() + s.invitation_days * interval '1 day'
     WHERE id = a.id;
    PERFORM portal_queue_account_message(a, 'password-reset',
                                         'https://portal.example.net/password-reset/' || t);
END
$$;

-- portal_reset(token, password): the link used once, unexpired: the password
-- set, the failures and the lock cleared; an invited account (its invitation
-- expired, renewed by the reset) becomes active.
CREATE FUNCTION portal_reset(p_token text, p_password text) RETURNS boolean
  LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    a portal_accounts;
BEGIN
    SELECT * INTO a FROM portal_accounts
     WHERE invite_hash = portal_token_hash(p_token) AND invite_expires_at > now()
       AND status IN ('invited', 'active') FOR UPDATE;
    IF NOT FOUND THEN
        RETURN false;
    END IF;
    UPDATE portal_accounts SET status = 'active', activated_at = coalesce(activated_at, now()),
           password_hash = crypt(p_password, gen_salt('bf', 6)),
           invite_hash = NULL, invite_expires_at = NULL, failed_logins = 0, locked_until = NULL
     WHERE id = a.id;
    RETURN true;
END
$$;

-- portal_unsubscribe(message_key): a reminder's withdrawal link, no login
-- (own-message-link): the reminders withdrawn (message-link), the flag
-- cleared; false for another message, or a closed account.
CREATE FUNCTION portal_unsubscribe(p_message_key uuid) RETURNS boolean
  LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    m portal_outbox;
BEGIN
    SELECT o.* INTO m FROM portal_outbox o JOIN portal_accounts a ON a.id = o.account_id
     WHERE o.message_key = p_message_key AND o.template = 'reminder' AND a.status <> 'closed';
    IF NOT FOUND THEN
        RETURN false;
    END IF;
    INSERT INTO portal_consent_events (owner_id, purpose, granted, at, source)
    VALUES (m.owner_id, 'reminders', false, now(), 'message-link');
    UPDATE portal_accounts SET reminders = false WHERE id = m.account_id;
    RETURN true;
END
$$;

-- portal_close(): the asker's account closed (rule 5): a closure message to
-- its address, its personal columns erased, its sessions ended (T281); the
-- consent events kept as proof; never reopened.
CREATE FUNCTION portal_close() RETURNS boolean
  LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    a portal_accounts;
BEGIN
    SELECT * INTO a FROM portal_accounts
     WHERE owner_id = NULLIF(current_setting('portal.owner_id', true), '')::integer
       AND status = 'active' FOR UPDATE;
    IF NOT FOUND THEN
        RETURN false;
    END IF;
    PERFORM portal_queue_account_message(a, 'closure', NULL);
    UPDATE portal_accounts SET status = 'closed', closed_at = now(), display_name = NULL, email = NULL,
           phone = NULL, password_hash = NULL, invite_hash = NULL, invite_expires_at = NULL,
           reminders = false, notify_by = 'none'
     WHERE id = a.id;
    UPDATE portal_sessions SET ended_at = now(), ended_by = 'closure'
     WHERE account_id = a.id AND ended_at IS NULL;
    RETURN true;
END
$$;

-- portal_desk_consent(owner_id, purpose, granted): the desk records an
-- owner's reminders' consent (at-desk, source desk), the flag beside it;
-- false for another purpose, no account or a closed one.
CREATE FUNCTION portal_desk_consent(p_owner_id integer, p_purpose text, p_granted boolean)
  RETURNS boolean
  LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
    IF p_purpose IS DISTINCT FROM 'reminders' OR p_granted IS NULL THEN
        RETURN false;
    END IF;
    UPDATE portal_accounts SET reminders = p_granted
     WHERE owner_id = p_owner_id AND status <> 'closed';
    IF NOT FOUND THEN
        RETURN false;
    END IF;
    INSERT INTO portal_consent_events (owner_id, purpose, granted, at, source)
    VALUES (p_owner_id, 'reminders', p_granted, now(), 'desk');
    RETURN true;
END
$$;

