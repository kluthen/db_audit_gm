CREATE TABLE portal_outbox (
    id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_key uuid        NOT NULL UNIQUE,
    account_id  integer     NOT NULL,
    owner_id    integer     NOT NULL,
    template    text        NOT NULL CHECK (template IN ('invitation', 'password-reset', 'closure',
                                                         'document-notice', 'reminder')),
    channel     text        NOT NULL CHECK (channel IN ('email', 'sms')),
    address     text        NOT NULL,
    document_id integer,
    animal_id   integer,
    due_on      date,
    payload     jsonb       NOT NULL,
    queued_at   timestamptz NOT NULL,
    sent_at     timestamptz,
    attempts    integer     NOT NULL DEFAULT 0,
    last_status text,
    provider_id uuid,
    failed_at   timestamptz,
    CHECK ((template = 'document-notice') = (document_id IS NOT NULL)),
    CHECK ((template = 'reminder') = (animal_id IS NOT NULL AND due_on IS NOT NULL)),
    CHECK ((sent_at IS NULL) = (provider_id IS NULL))
);
