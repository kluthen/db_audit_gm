CREATE UNIQUE INDEX portal_outbox_notice_idx ON portal_outbox (document_id, account_id)
    WHERE template = 'document-notice';
CREATE UNIQUE INDEX portal_outbox_reminder_idx ON portal_outbox (animal_id, due_on)
    WHERE template = 'reminder';
CREATE INDEX portal_outbox_unsent_idx ON portal_outbox (queued_at) WHERE sent_at IS NULL AND failed_at IS NULL;

