-- vet-portal's data model (v0.5 master spec 9.7, 13.1; specs/versions/v0.5/
-- vet-portal-domain.md, "The data model (step 4)"; access model 9.3; capture
-- W3 items 0 and 5): the centre's owners' portal, in the database the
-- scenario's domains: at: names (portal, on records, beside clinic and
-- office: ruled, D320).
--
-- The database convention (capture W2 item 3): gmctl load-data creates the
-- database when absent and runs this file connected to it as postgres, then
-- vet-core's data/keys.sql, this part's data/keys.sql and data/load.sql in one
-- session. This file never creates a database nor connects to one; it creates
-- its roles at top level (W3 item 0: model.node_creates reads them, so each
-- login role gets its secret) and names its database :"DBNAME". The login
-- roles' passwords are the game's secrets, set by load-data.
--
-- Every table prefixed portal_ in public (procedure 4); integer keys
-- GENERATED BY DEFAULT AS IDENTITY, written explicitly by the load and the
-- derivation in the ranges docs/gm.md "Part keys" documents, each sequence set
-- after its range (portal_accounts' at 20 000, T261). The core's and the
-- lab's keys (owner_id, animal_id, herd_id, keeper_id) are plain integers with
-- no foreign key. Column names follow W3 item 0.
--
-- Who sees what (W3 item 5, W3-e): row-level security enabled and forced on
-- every table; the tables belong to portal, NOLOGIN BYPASSRLS, so the
-- SECURITY DEFINER functions it owns reach every row; portal_api owns nothing
-- and does not bypass. The asker is
--     NULLIF(current_setting('portal.owner_id', true), '')::integer
-- inline in each policy (unset: no row), set by portal-api with
-- set_config('portal.owner_id', <owner id>, true) first in each request's
-- transaction, after portal_session(token). The policies are named
-- <table>_scope for portal_api, portal_sessions_purge for
-- portal_housekeeping. The keeper's clause and the ownership's start, which
-- own-rows policies hide from a keeper, are read by two pinned SECURITY
-- DEFINER helpers, portal_keeper_granted(animal, keeper) and
-- portal_owner_since(animal) (W3-e). The purposes' roles and their policies
-- (portal_sync, portal_dispatch, the ops schema) are the purposes' (capture
-- W3, Preflight corrections item 4), not this file's.
CREATE ROLE portal NOLOGIN BYPASSRLS;     -- owns everything; nobody logs in as it
CREATE ROLE portal_api LOGIN;             -- the portal's API (portal-api)
CREATE ROLE portal_housekeeping LOGIN;    -- the sessions' purge on records' pg_cron (data/cron.sql)

-- CONNECT by name (rule 10, T253); pg_cron runs a job only as a LOGIN role
-- with CONNECT (spec D405).
REVOKE CONNECT ON DATABASE :"DBNAME" FROM PUBLIC;
GRANT CONNECT ON DATABASE :"DBNAME" TO portal_api, portal_housekeeping;

-- The portal's own settings (rules 8, 9; T250, T251): no statement logging,
-- no parameters in the server's log, pgaudit without parameters, since
-- passwords pass through SQL.
ALTER DATABASE :"DBNAME" SET log_statement = 'none';
ALTER DATABASE :"DBNAME" SET log_min_duration_statement = -1;
ALTER DATABASE :"DBNAME" SET log_parameter_max_length = 0;
ALTER DATABASE :"DBNAME" SET log_parameter_max_length_on_error = 0;
ALTER DATABASE :"DBNAME" SET pgaudit.log_parameter = off;

-- The passwords' hashes (crypt, gen_salt('bf')) and the tokens' (digest).
CREATE EXTENSION IF NOT EXISTS pgcrypto;

GRANT USAGE, CREATE ON SCHEMA public TO portal;
SET ROLE portal;

-- --- Accounts and sessions ------------------------------------------------------------

-- One row: the customer's zone and offset (as the core's business_settings),
-- the session's idle limit and longest life, the lock-out, the one-time
-- link's life, the reminders' lead and hours (game values, rule 4, 7).
CREATE TABLE portal_settings (
    timezone           text    NOT NULL,
    utc_offset_hours   integer NOT NULL,
    idle_minutes       integer NOT NULL DEFAULT 30,
    session_hours      integer NOT NULL DEFAULT 12,
    lock_failures      integer NOT NULL DEFAULT 5,
    lock_minutes       integer NOT NULL DEFAULT 30,
    invitation_days    integer NOT NULL DEFAULT 14,
    reminder_lead_days integer NOT NULL DEFAULT 14,
    reminders_from     time    NOT NULL DEFAULT '08:00',
    reminders_until    time    NOT NULL DEFAULT '20:00'
);

-- One account per core owner but the clinic: account o is owner o for the
-- migrated accounts (2-10 000), new ones from 20 001 (T261). invite_hash is
-- the SHA-256 of the account's open one-time link, an invitation's or a
-- reset's (W3-e), with its expiry; reminders is the flag beside the consent
-- events, which no job reads (rule 6). Closing erases the personal columns
-- (rule 5).
CREATE TABLE portal_accounts (
    id                integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id          integer     NOT NULL UNIQUE,
    kind              text        NOT NULL CHECK (kind IN ('person', 'stable', 'holding')),
    display_name      text,
    email             text        UNIQUE,
    phone             text,
    status            text        NOT NULL DEFAULT 'invited'
                                  CHECK (status IN ('invited', 'active', 'closed')),
    invited_at        timestamptz NOT NULL,
    invite_hash       text        UNIQUE,
    invite_expires_at timestamptz,
    activated_at      timestamptz,
    password_hash     text,
    failed_logins     integer     NOT NULL DEFAULT 0,
    locked_until      timestamptz,
    last_login_at     timestamptz,
    notify_by         text        NOT NULL DEFAULT 'email' CHECK (notify_by IN ('email', 'sms', 'none')),
    reminders         boolean     NOT NULL DEFAULT false,
    closed_at         timestamptz,
    synced_at         timestamptz NOT NULL,
    CHECK ((status = 'closed') = (closed_at IS NOT NULL)),
    CHECK (status <> 'active' OR (activated_at IS NOT NULL AND password_hash IS NOT NULL)),
    CHECK ((invite_hash IS NULL) = (invite_expires_at IS NULL))
);
CREATE INDEX portal_accounts_email_idx ON portal_accounts (lower(email));

-- Sessions by the SHA-256 of their token (rule 4, T277); ended by a logout, an
-- idle half hour, the twelve hours' expiry, or the account's closure.
CREATE TABLE portal_sessions (
    id           integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id   integer     NOT NULL REFERENCES portal_accounts,
    token_hash   text        NOT NULL UNIQUE,
    created_at   timestamptz NOT NULL,
    last_seen_at timestamptz NOT NULL,
    expires_at   timestamptz NOT NULL,
    ended_at     timestamptz,
    ended_by     text        CHECK (ended_by IN ('logout', 'idle', 'expiry', 'closure')),
    CHECK ((ended_at IS NULL) = (ended_by IS NULL))
);
CREATE INDEX portal_sessions_account_idx ON portal_sessions (account_id);
CREATE INDEX portal_sessions_ended_idx ON portal_sessions ((coalesce(ended_at, expires_at)));

