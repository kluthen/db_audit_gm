-- vet-housing's data model (v0.5 master spec 9.5; specs/versions/v0.5/
-- vet-housing-domain.md, "The data model"; capture W3 items 0 and 3): the
-- centre's 64 units, the placements of the core's stays in them, each stay's
-- feeding plans and care log, the displays, and the unit board a display
-- reads. In the core's database (lands_with: vet-core): each board read is
-- one statement joining a unit to the core's animal_board.
--
-- The database convention (v0.5 capture W2, item 3): gmctl load-data runs
-- this file after the core's schema.sql and load.sql, connected to the same
-- database (psql -d <database>) as the postgres OS user, then data/load.sql
-- with the core's data/keys.sql streamed ahead of it. So this file never
-- creates a database nor connects to one; it creates its roles at top level
-- and names its database :"DBNAME". The login roles' passwords are the
-- game's secrets, set by load-data, never written here.
--
-- Tables in public, prefixed housing_, owned by housing; integer keys
-- GENERATED BY DEFAULT AS IDENTITY, written explicitly by the load, each
-- sequence set after its range (load.sql's end). The core's keys (section,
-- stay, staff) are plain integer columns with no foreign key: a placement on
-- a stay that does not exist is an invariant broken (the coherence check's,
-- data/coherence.yaml), never refused here. Column names follow capture W3
-- item 0 (a time ends _at, a date _on, a staff member _by).
CREATE ROLE housing NOLOGIN;        -- owns the tables and the board
CREATE ROLE housing_app LOGIN;      -- the practice software's housing screens (pms)
CREATE ROLE housing_ward LOGIN;     -- the ward service's writes (ward, D287)

GRANT CONNECT ON DATABASE :"DBNAME" TO housing_app, housing_ward;

-- What the board reads of the core, given to its owner: the core's display
-- view, the customer's zone for "today", and of the stay and the animal the
-- two columns animal_board leaves out (the stay's reason, the animal's
-- birth date, for its age). The board's join, unit -> open placement ->
-- stay -> animal, is D287's chain.
GRANT SELECT ON animal_board, business_settings TO housing;
GRANT SELECT (id, animal_id, reason) ON stays TO housing;
GRANT SELECT (id, born_on) ON animals TO housing;

-- The tables are housing's: it may create them in public for this file only.
GRANT USAGE, CREATE ON SCHEMA public TO housing;
SET ROLE housing;

-- --- Reference ------------------------------------------------------------------

-- 1-22 the horse barn, 23-32 the farm barn, 33-64 the domestic wards
-- (docs/gm.md, "The units"). A box fits a horse, a stall cattle, a pen sheep
-- or goats, a kennel a dog, a cage a cat or a small animal; an isolation or
-- an intensive-care unit any species of its section. The hygiene is a state;
-- whether a unit is occupied is not: its open placement says so.
CREATE TABLE housing_units (
    id             integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id     integer     NOT NULL,                -- the core's sections.id
    code           text        NOT NULL UNIQUE,         -- H-01, F-03, D-12
    kind           text        NOT NULL CHECK (kind IN ('box', 'stall', 'pen', 'kennel', 'cage')),
    isolation      boolean     NOT NULL DEFAULT false,
    intensive      boolean     NOT NULL DEFAULT false,
    state          text        NOT NULL DEFAULT 'clean'
                   CHECK (state IN ('clean', 'to-clean', 'out-of-service')),
    state_since_at timestamptz NOT NULL DEFAULT now(),
    CHECK (NOT (isolation AND intensive))
);

-- One display on each unit; a replaced one removed (removed_on), its
-- successor installed the same day: unit -> display goes through this table.
CREATE TABLE housing_displays (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id      integer NOT NULL REFERENCES housing_units,
    serial       text    NOT NULL UNIQUE,
    installed_on date    NOT NULL,
    removed_on   date,
    CHECK (removed_on IS NULL OR removed_on >= installed_on)
);
CREATE UNIQUE INDEX housing_displays_one_in_place ON housing_displays (unit_id)
    WHERE removed_on IS NULL;

-- --- Placements, plans, care log ------------------------------------------------

-- Which stay is in which unit, from when until when (open while placed): one
-- animal per unit, one unit per stay. A move ends one and opens the next at
-- one instant, in one transaction.
CREATE TABLE housing_placements (
    id        integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id   integer     NOT NULL REFERENCES housing_units,
    stay_id   integer     NOT NULL,                     -- the core's stays.id
    from_at   timestamptz NOT NULL,
    until_at  timestamptz,
    reason    text        NOT NULL CHECK (reason IN ('admission', 'move', 'isolation')),
    placed_by integer     NOT NULL,                     -- the core's staff.id, a nurse
    CHECK (until_at IS NULL OR until_at >= from_at)
);
CREATE UNIQUE INDEX housing_placements_one_per_unit ON housing_placements (unit_id)
    WHERE until_at IS NULL;
CREATE UNIQUE INDEX housing_placements_one_per_stay ON housing_placements (stay_id)
    WHERE until_at IS NULL;
CREATE INDEX housing_placements_stay_idx ON housing_placements (stay_id);

-- A stay's diet (from its species' short list) or a vet's nil-by-mouth order,
-- in force from until; an order in force overrides the diet on the board.
CREATE TABLE housing_feeding_plans (
    id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stay_id     integer     NOT NULL,                   -- the core's stays.id
    kind        text        NOT NULL CHECK (kind IN ('diet', 'nil-by-mouth')),
    diet        text,
    meals_a_day integer     CHECK (meals_a_day BETWEEN 1 AND 6),
    from_at     timestamptz NOT NULL,
    until_at    timestamptz,
    set_by      integer     NOT NULL,                   -- the core's staff.id, a nurse
    note        text,
    CHECK ((kind = 'diet') = (diet IS NOT NULL AND meals_a_day IS NOT NULL)),
    CHECK (until_at IS NULL OR until_at >= from_at)
);
CREATE INDEX housing_feeding_plans_stay_idx ON housing_feeding_plans (stay_id);

-- Each action taken at a unit, for its occupant at the time (stay_id), or
-- for the emptied unit (none): written once, never updated. Never a dose:
-- medicines given are the core's administrations (rule 5).
CREATE TABLE housing_care_events (
    id      integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id integer     NOT NULL REFERENCES housing_units,
    stay_id integer,                                    -- the core's stays.id
    kind    text        NOT NULL CHECK (kind IN ('feeding', 'water', 'mucking-out', 'bedding', 'walk',
                                                 'grooming', 'check', 'disinfection')),
    eaten   text        CHECK (eaten IN ('all', 'part', 'none')),
    done_at timestamptz NOT NULL,
    done_by integer     NOT NULL,                       -- the core's staff.id, a carer
    note    text,
    CHECK ((kind = 'feeding') = (eaten IS NOT NULL)),
    CHECK (kind <> 'feeding' OR stay_id IS NOT NULL),
    CHECK (kind <> 'disinfection' OR stay_id IS NULL)
);
-- The board's day of care, by unit and time (without it, trap T156).
CREATE INDEX housing_care_events_unit_time_idx ON housing_care_events (unit_id, done_at);

-- --- The unit board ----------------------------------------------------------------

-- What a display shows, one row per unit: the unit; its open placement; the
-- stay and its animal, from the core's animal_board (identity, alerts, the
-- day's doses), the stay's reason and the animal's age; the plan in force, a
-- nil-by-mouth order overriding the diet; the day's feedings at this unit
-- (count, the last, what was eaten), the meals its species' rounds have made
-- due since it was placed here today (a round inside a nil-by-mouth order
-- makes none), and its last check. "Today" is the customer's
-- (business_settings). An empty unit's row carries the unit only.
-- Never an owner, a contact or a natural identifier (rule 1, core rule 10).
-- The feeding rounds are the clinic's game values (rule 4): horses 06, 12,
-- 17 and 21; cattle, sheep and goats 07 and 16; dogs 08 and 17; cats and
-- small animals 08, 13 and 18.
CREATE VIEW housing_unit_board AS
SELECT u.id AS unit_id, u.code, u.section_id, u.kind, u.isolation, u.intensive, u.state,
       p.id AS placement_id, p.from_at AS placed_at,
       p.stay_id, ab.admitted_at, s.reason,
       ab.animal_id, ab.name, ab.species, ab.breed, ab.sex,
       extract(year FROM age(t.today, a.born_on))::integer AS age_years,
       ab.alerts, ab.doses_today, ab.doses_given_today, ab.next_dose_at,
       f.kind AS plan_kind, f.diet, f.meals_a_day, f.until_at AS plan_until_at,
       c.feedings_today, c.last_fed_at, c.last_eaten,
       CASE WHEN p.id IS NULL THEN NULL WHEN f.kind = 'diet' THEN least(f.meals_a_day, r.rounds) ELSE 0 END
           AS meals_due,
       k.last_check_at
  FROM housing_units AS u
 CROSS JOIN LATERAL (SELECT (now() AT TIME ZONE b.timezone)::date AS today, b.timezone,
                            date_trunc('day', now() AT TIME ZONE b.timezone) AT TIME ZONE b.timezone AS since
                       FROM business_settings AS b) AS t
  LEFT JOIN housing_placements AS p ON p.unit_id = u.id AND p.until_at IS NULL
  LEFT JOIN stays AS s ON s.id = p.stay_id
  LEFT JOIN animal_board AS ab ON ab.stay_id = p.stay_id
  LEFT JOIN animals AS a ON a.id = ab.animal_id
  LEFT JOIN LATERAL (SELECT fp.kind, fp.diet, fp.meals_a_day, fp.until_at
                       FROM housing_feeding_plans AS fp
                      WHERE p.id IS NOT NULL AND fp.stay_id = p.stay_id AND fp.from_at <= now()
                        AND (fp.until_at IS NULL OR fp.until_at > now())
                      ORDER BY fp.kind = 'nil-by-mouth' DESC, fp.from_at DESC, fp.id DESC
                      LIMIT 1) AS f ON true
  LEFT JOIN LATERAL (SELECT count(*) AS feedings_today, max(e.done_at) AS last_fed_at,
                            (array_agg(e.eaten ORDER BY e.done_at DESC, e.id DESC))[1] AS last_eaten
                       FROM housing_care_events AS e
                      WHERE e.unit_id = u.id AND e.done_at >= t.since AND e.kind = 'feeding'
                        AND e.stay_id = p.stay_id
                     HAVING p.id IS NOT NULL) AS c ON true
  LEFT JOIN LATERAL (SELECT count(*)::integer AS rounds
                       FROM unnest(CASE ab.species WHEN 'horse' THEN ARRAY[6, 12, 17, 21]
                                                   WHEN 'cattle' THEN ARRAY[7, 16]
                                                   WHEN 'sheep' THEN ARRAY[7, 16]
                                                   WHEN 'goat' THEN ARRAY[7, 16]
                                                   WHEN 'dog' THEN ARRAY[8, 17]
                                                   ELSE ARRAY[8, 13, 18] END) AS h
                      WHERE p.id IS NOT NULL
                        AND (t.today + make_interval(hours => h)) AT TIME ZONE t.timezone
                            BETWEEN greatest(t.since, p.from_at) AND now()
                        AND NOT EXISTS (SELECT 1 FROM housing_feeding_plans AS n
                                         WHERE n.stay_id = p.stay_id AND n.kind = 'nil-by-mouth'
                                           AND (t.today + make_interval(hours => h)) AT TIME ZONE t.timezone
                                               >= n.from_at
                                           AND (t.today + make_interval(hours => h)) AT TIME ZONE t.timezone
                                               < coalesce(n.until_at, 'infinity'))) AS r ON true
  LEFT JOIN LATERAL (SELECT max(e.done_at) AS last_check_at
                       FROM housing_care_events AS e
                      WHERE p.id IS NOT NULL AND e.unit_id = u.id AND e.done_at >= p.from_at
                        AND e.kind = 'check' AND e.stay_id = p.stay_id) AS k ON true;

RESET ROLE;
REVOKE CREATE ON SCHEMA public FROM housing;

-- --- Grants (vet-housing-domain.md, "Application roles and grants") ----------------

-- Writing a table whose id is an identity column needs no privilege on its
-- sequence.

-- The practice software's housing screens: every housing table and the
-- board; of the core's, what placing, moving and releasing read. They place,
-- move and release, set diets and orders, and mark a unit to clean; never
-- the units' or displays' other columns, never the care log.
GRANT SELECT ON housing_units, housing_displays, housing_placements, housing_feeding_plans,
                housing_care_events, housing_unit_board
   TO housing_app;
GRANT SELECT (id, animal_id, section_id, admitted_at, discharged_at, outcome) ON stays TO housing_app;
GRANT SELECT (id, species) ON animals TO housing_app;
GRANT SELECT (animal_id, kind, from_at, until_at) ON alerts TO housing_app;
GRANT SELECT (id, kind) ON staff TO housing_app;
GRANT INSERT, UPDATE ON housing_placements, housing_feeding_plans TO housing_app;
GRANT UPDATE (state, state_since_at) ON housing_units TO housing_app;

-- The ward service's writes, the carers' actions from the displays: a care
-- event added, a unit marked clean; nothing else (rule 7). A display cannot
-- move an animal or touch the record.
GRANT SELECT ON housing_units, housing_placements, housing_feeding_plans, housing_care_events,
                housing_unit_board
   TO housing_ward;
GRANT SELECT (id, kind) ON staff TO housing_ward;
GRANT INSERT ON housing_care_events TO housing_ward;
-- A feeding's eaten is a hash of its id, so the service takes the id first.
GRANT USAGE ON SEQUENCE housing_care_events_id_seq TO housing_ward;
GRANT UPDATE (state, state_since_at) ON housing_units TO housing_ward;

-- The displays' reads, through the ward service's pool: the board only,
-- beside the core's animal_board (the core's grant).
GRANT SELECT ON housing_unit_board TO vet_display;

-- The back office on the standby: every housing table, as every core table
-- (the occupancy measure of purpose 9 reads housing_units and
-- housing_placements; docs/gm.md, "The occupancy measure").
GRANT SELECT ON housing_units, housing_displays, housing_placements, housing_feeding_plans,
                housing_care_events, housing_unit_board
   TO vet_reports;
