-- vet-lab's data model (v0.5 master spec 9.3; specs/versions/v0.5/
-- vet-lab-domain.md, "The data model (step 4)"; capture W3 items 0 and 1):
-- the centre's laboratory, in the database the scenario's domains: at: names
-- (lab, on the lab node: answer 1, a node of its own).
--
-- The database convention (capture W2 item 3): gmctl load-data creates the
-- database when absent and runs this file connected to it as postgres, then
-- vet-core's data/keys.sql, this part's data/keys.sql and data/load.sql in one
-- session. This file never creates a database nor connects to one; it creates
-- its roles at top level (W3 item 0: model.node_creates reads them, so each
-- login role gets its secret) and names its database :"DBNAME". The login
-- roles' passwords are the game's secrets, set by load-data.
--
-- Every table prefixed lab_ in public (procedure 4); integer keys GENERATED
-- BY DEFAULT AS IDENTITY, written explicitly by the load in the ranges
-- docs/gm.md "Part keys" documents, each sequence set after its range. The
-- core's keys (animal_id, request_id, consultation_id, practice_id, the staff
-- ids) and vet-machinery's machine_id are plain integers with no foreign key.
-- Column names follow W3 item 0: a time ends _at, a date _on, a staff member
-- _by, a key <thing>_id.
CREATE ROLE lab NOLOGIN;              -- owns everything
CREATE ROLE lab_app LOGIN;            -- the information system (lis)
CREATE ROLE lab_api LOGIN;            -- the order API (lab-api)
CREATE ROLE lab_instruments LOGIN;    -- the analysers' middleware (lis, connection lab-instruments)
CREATE ROLE lab_dispatch LOGIN;       -- the centre's jobs posting results and send-outs (purposes 2, 3)
CREATE ROLE lab_reports LOGIN;        -- the periodic reports and statements, read only

REVOKE CONNECT ON DATABASE :"DBNAME" FROM PUBLIC;
GRANT CONNECT ON DATABASE :"DBNAME" TO lab_app, lab_api, lab_instruments, lab_dispatch, lab_reports;

GRANT USAGE, CREATE ON SCHEMA public TO lab;
SET ROLE lab;

-- --- Reference ---------------------------------------------------------------------

-- One row: the customer's zone and offset (the core's business_settings, a
-- copy of the lab's own on its node), the handling fee, the urgent surcharge,
-- the critical call's limit (rules 6, 13).
CREATE TABLE lab_settings (
    timezone              text         NOT NULL,
    utc_offset_hours      integer      NOT NULL,
    handling_fee          numeric(8,2) NOT NULL DEFAULT 6.50,
    urgent_surcharge_pct  integer      NOT NULL DEFAULT 50,
    critical_call_minutes integer      NOT NULL DEFAULT 60,
    retention_years       integer      NOT NULL DEFAULT 5
);
CREATE UNIQUE INDEX lab_settings_one_row ON lab_settings ((true));

CREATE TABLE lab_analytes (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL,
    unit text,
    kind text NOT NULL CHECK (kind IN ('numeric', 'text'))
);

-- 1-150 tests (115-150 sent out), 151-180 panels (the test catalogue, D372).
CREATE TABLE lab_tests (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             text    NOT NULL UNIQUE,
    name             text    NOT NULL,
    is_panel         boolean NOT NULL,
    discipline       text    NOT NULL CHECK (discipline IN ('haematology', 'biochemistry', 'blood-gas',
                         'coagulation', 'urinalysis', 'cytology', 'microbiology', 'serology', 'residue',
                         'histopathology', 'molecular', 'endocrinology', 'toxicology')),
    sample_type      text    NOT NULL CHECK (sample_type IN ('edta-blood', 'serum', 'citrate-plasma',
                         'heparin-blood', 'urine', 'milk', 'swab', 'tissue', 'faeces')),
    turnaround_hours integer NOT NULL,
    performed        text    NOT NULL CHECK (performed IN ('in-house', 'sent-out')),
    external_code    text,                         -- the external lab's code, sent-out tests only
    diagnosis_code   text,                         -- the core's, when the test detects a listed disease
    CHECK ((performed = 'sent-out') = (external_code IS NOT NULL))
);

CREATE TABLE lab_test_analytes (
    test_id    integer NOT NULL REFERENCES lab_tests,
    analyte_id integer NOT NULL REFERENCES lab_analytes,
    position   integer NOT NULL,
    PRIMARY KEY (test_id, analyte_id)
);

-- Per analyte and species, adults only, dated: a result keeps the interval it
-- was flagged against (answer 9). Critical limits where they matter.
CREATE TABLE lab_reference_intervals (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analyte_id    integer NOT NULL REFERENCES lab_analytes,
    species       text    NOT NULL CHECK (species IN ('dog', 'cat', 'horse', 'cattle', 'sheep', 'goat')),
    low           numeric NOT NULL,
    high          numeric NOT NULL,
    critical_low  numeric,
    critical_high numeric,
    valid_from    date    NOT NULL,
    valid_until   date,                            -- open while in force
    CHECK (low < high)
);
CREATE INDEX lab_reference_intervals_analyte_idx ON lab_reference_intervals (analyte_id, species, valid_from);

-- One list, revised each 1 January (answer 13).
CREATE TABLE lab_prices (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_id     integer      NOT NULL REFERENCES lab_tests,
    price       numeric(8,2) NOT NULL,
    valid_from  date         NOT NULL,
    valid_until date
);
CREATE INDEX lab_prices_test_idx ON lab_prices (test_id, valid_from);

-- 1 the centre (internal, never charged); 2-121 the region's practices, the
-- core's referring practice 3 (a - 1), each its callback.
CREATE TABLE lab_accounts (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         text    NOT NULL CHECK (kind IN ('internal', 'practice')),
    practice_id  integer,                          -- the core's referring_practices.id
    callback_url text,
    opened_on    date    NOT NULL,
    closed_on    date,
    CHECK ((kind = 'internal') = (practice_id IS NULL))
);

-- --- Orders and samples ---------------------------------------------------------

-- One accession per submission. The centre's: the core's animal,
-- consultation and requesting vet, client_ref C-<consultation>-<priority>; a
-- practice's: its patient reference and its client's surname, never a core
-- animal (answer 4). client_ref is the idempotency key, unique per account.
-- client_surname: a practice's client, or the centre's owner as the lookup
-- API answers it (lab.identity). State: ordered, received (received_at),
-- completed (completed_at, every test final) or cancelled (cancelled_at).
CREATE TABLE lab_orders (
    id                 integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id         integer     NOT NULL REFERENCES lab_accounts,
    client_ref         text        NOT NULL,
    priority           text        NOT NULL CHECK (priority IN ('routine', 'urgent')),
    animal_id          integer,                    -- the centre's
    consultation_id    integer,                    -- the centre's
    requested_by       integer,                    -- the centre's requesting vet (staff)
    patient_ref        text,                       -- a practice's
    client_surname     text,
    species            text,
    sex                text,
    born_on            date,
    microchip          text,
    ueln               text,
    ear_tag            text,
    clinical_notes     text,
    withdrawal_ends_on date,                       -- a residue screening's (answer 11)
    ordered_at         timestamptz NOT NULL,
    received_at        timestamptz,
    completed_at       timestamptz,
    cancelled_at       timestamptz,
    UNIQUE (account_id, client_ref)
);
CREATE INDEX lab_orders_ordered_at_idx ON lab_orders (ordered_at);

CREATE TABLE lab_samples (
    id           integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     integer     NOT NULL REFERENCES lab_orders,
    label        text        NOT NULL UNIQUE,      -- the tube's barcode
    sample_type  text        NOT NULL,
    collected_at timestamptz,
    collected_by integer,                          -- the centre's staff
    received_at  timestamptz,
    condition    text        CHECK (condition IN ('fit', 'haemolysed', 'lipaemic', 'icteric', 'clotted',
                                                  'under-filled', 'too-old', 'unlabelled')),
    custody      boolean     NOT NULL DEFAULT false,   -- a chain of custody applies (answer 10)
    keep_until   timestamptz,
    disposed_at  timestamptz
);
CREATE INDEX lab_samples_order_idx ON lab_samples (order_id);

-- One per orderable item (a panel one test, billed once). States: ordered,
-- in-progress or sent-out, technical, released; or not-performed (an unfit
-- sample), cancelled. The feed's time is released_at, not_performed_at or
-- cancelled_at.
CREATE TABLE lab_order_tests (
    id                   integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id             integer     NOT NULL REFERENCES lab_orders,
    sample_id            integer     REFERENCES lab_samples,
    test_id              integer     NOT NULL REFERENCES lab_tests,
    request_id           integer,                  -- the core's, the centre's orders
    routing              text        NOT NULL CHECK (routing IN ('in-house', 'sent-out')),
    add_on               boolean     NOT NULL DEFAULT false,
    status               text        NOT NULL DEFAULT 'ordered'
                                     CHECK (status IN ('ordered', 'in-progress', 'sent-out', 'technical',
                                                       'released', 'not-performed', 'cancelled')),
    not_performed_reason text,
    not_performed_at     timestamptz,
    technical_by         integer,                  -- a lab technician (staff 71-78)
    technical_at         timestamptz,
    released_by          integer,                  -- a clinical pathologist (staff 79-80)
    released_at          timestamptz,
    cancelled_at         timestamptz,
    comment              text
);
CREATE INDEX lab_order_tests_order_idx ON lab_order_tests (order_id);
CREATE INDEX lab_order_tests_released_at_idx ON lab_order_tests (released_at);

CREATE TABLE lab_sample_events (
    id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_id   integer     NOT NULL REFERENCES lab_samples,
    kind        text        NOT NULL CHECK (kind IN ('received', 'stored', 'moved', 'sent-out', 'forwarded',
                                                     'disposed')),
    at          timestamptz NOT NULL,
    recorded_by integer,                           -- staff
    place       text,
    other_party text,                              -- a chain of custody's, by name
    condition   text,
    seal_number text
);
CREATE INDEX lab_sample_events_sample_idx ON lab_sample_events (sample_id);

-- --- Work ---------------------------------------------------------------------------

CREATE TABLE lab_qc_runs (
    id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id  integer     NOT NULL,              -- vet-machinery's analysers 1-6
    level       integer     NOT NULL CHECK (level BETWEEN 1 AND 3),
    control_lot text        NOT NULL,
    run_at      timestamptz NOT NULL,
    run_by      integer,
    outcome     text        NOT NULL CHECK (outcome IN ('pass', 'fail')),
    rule_broken text        CHECK (rule_broken IN ('1-3s', '2-2s', 'R-4s', '4-1s', '10-x')),
    action      text        NOT NULL DEFAULT 'none'
                            CHECK (action IN ('none', 'rerun', 'recalibrated', 'results-held'))
);
CREATE INDEX lab_qc_runs_machine_idx ON lab_qc_runs (machine_id, run_at);

CREATE TABLE lab_batches (
    id           integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id   integer     NOT NULL,
    qc_run_id    integer     REFERENCES lab_qc_runs,   -- the QC run in force
    started_at   timestamptz NOT NULL,
    uploaded_at  timestamptz,
    result_count integer     NOT NULL DEFAULT 0
);
CREATE INDEX lab_batches_machine_idx ON lab_batches (machine_id, started_at);

-- One per analyte; an amendment a new row superseding the first, both kept
-- (rule 3). The result in force is the one no row supersedes.
CREATE TABLE lab_results (
    id               integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_test_id    integer     NOT NULL REFERENCES lab_order_tests,
    analyte_id       integer     NOT NULL REFERENCES lab_analytes,
    batch_id         integer     REFERENCES lab_batches,   -- none for bench work and send-outs
    numeric_value    numeric,
    text_value       text,
    flag             text        CHECK (flag IN ('normal', 'low', 'high', 'critical-low', 'critical-high')),
    interval_id      integer     REFERENCES lab_reference_intervals,
    measured_at      timestamptz NOT NULL,
    supersedes_id    integer     REFERENCES lab_results,
    amended_by       integer,
    amended_at       timestamptz,
    amendment_reason text,
    CHECK ((numeric_value IS NULL) <> (text_value IS NULL))
);
CREATE INDEX lab_results_order_test_idx ON lab_results (order_test_id);
CREATE INDEX lab_results_supersedes_idx ON lab_results (supersedes_id);

CREATE TABLE lab_critical_calls (
    id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    result_id       integer     NOT NULL REFERENCES lab_results,
    called_at       timestamptz NOT NULL,
    called_by       integer,                       -- a lab technician
    called_staff_id integer,                       -- the requesting vet
    called_person   text,                          -- a person at the practice, by name
    read_back       boolean     NOT NULL DEFAULT true
);

CREATE TABLE lab_notifications (
    id                  integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_test_id       integer     NOT NULL REFERENCES lab_order_tests,
    diagnosis_code      text        NOT NULL,      -- the core's
    category            text        NOT NULL CHECK (category IN ('A', 'other')),
    suspected_at        timestamptz NOT NULL,
    notified_at         timestamptz,               -- the push (vet-notifiable-diseases)
    channel             text,
    authority_ref       text,
    forwarded_sample_id integer     REFERENCES lab_samples,   -- category A
    official_lab_ref    text
);

-- --- Round trips and billing --------------------------------------------------------

-- The external lab's round trip: send_key the correlation key, sent again on
-- a retry (W3 item 1: md5('vet-lab-send-out:' || id)::uuid at load).
CREATE TABLE lab_send_outs (
    id                  integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_test_id       integer     NOT NULL REFERENCES lab_order_tests,
    send_key            uuid        NOT NULL UNIQUE,
    external_accession  text,                      -- the external lab's
    packed_at           timestamptz NOT NULL,
    sent_at             timestamptz,
    accepted_at         timestamptz,
    answered_at         timestamptz,
    due_by              timestamptz,
    status              text        NOT NULL DEFAULT 'packed'
                                    CHECK (status IN ('packed', 'sent', 'accepted', 'resulted'))
);
CREATE INDEX lab_send_outs_order_test_idx ON lab_send_outs (order_test_id);

-- The practices' deliveries (purpose 2): delivery_key one per order, kind and
-- revision, kept across attempts; one row an attempt.
CREATE TABLE lab_callbacks (
    id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        integer     NOT NULL REFERENCES lab_orders,
    kind            text        NOT NULL CHECK (kind IN ('interim', 'final', 'amended')),
    delivery_key    text        NOT NULL,
    attempt         integer     NOT NULL DEFAULT 1,
    posted_at       timestamptz NOT NULL,
    http_status     integer,
    acknowledged_at timestamptz
);
CREATE INDEX lab_callbacks_order_idx ON lab_callbacks (order_id);

-- Charged at accession, billable at release, voided on a cancellation or an
-- unfit sample (D304, rule 13); the centre's account never charged.
CREATE TABLE lab_charges (
    id            integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    integer      NOT NULL REFERENCES lab_accounts,
    order_id      integer      NOT NULL REFERENCES lab_orders,
    order_test_id integer      REFERENCES lab_order_tests,   -- none for the handling fee
    kind          text         NOT NULL CHECK (kind IN ('test', 'handling', 'urgent')),
    price         numeric(8,2) NOT NULL,
    amount        numeric(8,2) NOT NULL,
    billable_on   date,
    voided_at     timestamptz
);
CREATE INDEX lab_charges_account_idx ON lab_charges (account_id, billable_on);

RESET ROLE;
REVOKE CREATE ON SCHEMA public FROM lab;

-- --- Grants (vet-lab-domain.md, "Application roles and grants", D302, D304) ----------

-- The information system: every table read; the work written, never the
-- reference tables.
GRANT SELECT ON ALL TABLES IN SCHEMA public TO lab_app;
GRANT INSERT, UPDATE ON lab_orders, lab_samples, lab_order_tests, lab_sample_events, lab_results,
                        lab_critical_calls, lab_notifications, lab_qc_runs, lab_charges TO lab_app;
GRANT USAGE ON SEQUENCE lab_orders_id_seq, lab_samples_id_seq, lab_order_tests_id_seq,
                        lab_sample_events_id_seq, lab_results_id_seq, lab_critical_calls_id_seq,
                        lab_notifications_id_seq, lab_qc_runs_id_seq, lab_charges_id_seq TO lab_app;

-- The order API: the catalogue, the accounts, orders, their tests and
-- results; it writes the intake (orders, samples, order tests) and the
-- external lab's answers (the send-out, its results).
GRANT SELECT ON lab_tests, lab_test_analytes, lab_analytes, lab_accounts, lab_orders, lab_samples,
                lab_order_tests, lab_results, lab_send_outs TO lab_api;
GRANT INSERT ON lab_orders, lab_samples, lab_order_tests, lab_results TO lab_api;
GRANT UPDATE (status, answered_at) ON lab_send_outs TO lab_api;
GRANT USAGE ON SEQUENCE lab_orders_id_seq, lab_samples_id_seq, lab_order_tests_id_seq,
                        lab_results_id_seq TO lab_api;

-- The analysers' middleware: what a run needs (the order's species and the
-- test's discipline beside the document's list, to flag and to pick a
-- bench's tests), batches and results written.
GRANT SELECT ON lab_samples, lab_order_tests, lab_analytes, lab_test_analytes, lab_reference_intervals,
                lab_qc_runs TO lab_instruments;
GRANT SELECT (id, species, priority) ON lab_orders TO lab_instruments;
GRANT SELECT (id, code, discipline) ON lab_tests TO lab_instruments;
GRANT SELECT, INSERT, UPDATE ON lab_batches TO lab_instruments;
GRANT INSERT ON lab_results TO lab_instruments;
GRANT USAGE ON SEQUENCE lab_batches_id_seq, lab_results_id_seq TO lab_instruments;

-- The dispatch jobs: what a delivery and a send-out carry; callbacks,
-- send-outs, sent-out events and the notifications' sent columns written.
GRANT SELECT ON lab_orders, lab_order_tests, lab_results, lab_accounts, lab_samples, lab_tests,
                lab_analytes, lab_callbacks, lab_send_outs, lab_notifications TO lab_dispatch;
GRANT INSERT, UPDATE ON lab_callbacks, lab_send_outs TO lab_dispatch;
GRANT INSERT ON lab_sample_events TO lab_dispatch;
GRANT UPDATE (notified_at, channel, authority_ref) ON lab_notifications TO lab_dispatch;
GRANT USAGE ON SEQUENCE lab_callbacks_id_seq, lab_send_outs_id_seq, lab_sample_events_id_seq TO lab_dispatch;

-- The reports: every table, nothing written.
GRANT SELECT ON ALL TABLES IN SCHEMA public TO lab_reports;
