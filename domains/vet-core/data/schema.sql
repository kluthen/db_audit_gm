-- vet-core's data model (v0.5 master spec 9.2; specs/versions/v0.5/
-- vet-core-domain.md, "The data model"): the medical record of one centre of
-- Aldermoor Veterinary Hospitals, in the database the scenario's domains:
-- at: names (clinic by convention).
--
-- The database convention (v0.5 capture W2, item 3): gmctl load-data creates
-- the database when absent (owner postgres, CONNECT revoked from PUBLIC) and
-- runs this file connected to it (psql -d <database>) as the postgres OS
-- user, then data/keys.sql and data/load.sql in one session. So this file
-- never creates a database nor connects to one; it creates its roles at top
-- level and names its database :"DBNAME". The login roles' passwords are the
-- game's secrets, set by load-data, never written here.
--
-- Tables are unprefixed in public (the core is no part); integer keys
-- GENERATED BY DEFAULT AS IDENTITY, written explicitly by the load in the
-- ranges docs/gm.md "Core keys" documents, each sequence set after its range
-- (load.sql's end). Parts refer to these keys by id with no foreign key, so a
-- part's schema runs here or in an instance of its own.
CREATE ROLE vet NOLOGIN;            -- owns everything
CREATE ROLE vet_app LOGIN;          -- the practice-management software (pms)
CREATE ROLE vet_lookup LOGIN;       -- the lookup API (clinic-api)
CREATE ROLE vet_display LOGIN;      -- the housing displays, through animal_board
CREATE ROLE vet_reports LOGIN;      -- the back office, read only

-- CONNECT by name (vet-core-domain.md, "CONNECT by name"; vet-portal rule 10):
-- the portal's role on the same instance cannot open the record's database.
REVOKE CONNECT ON DATABASE :"DBNAME" FROM PUBLIC;
GRANT CONNECT ON DATABASE :"DBNAME" TO vet_app, vet_lookup, vet_display, vet_reports;

-- The tables are vet's: it may create them in public for this file only.
GRANT USAGE, CREATE ON SCHEMA public TO vet;
SET ROLE vet;

-- --- Places and people -------------------------------------------------------

-- One row, written by load.sql from load-data's variables: the customer's
-- zone (Etc/GMT-N for UTC+N) and its offset; every site is in it.
CREATE TABLE business_settings (
    timezone         text    NOT NULL,
    utc_offset_hours integer NOT NULL,
    company          text    NOT NULL DEFAULT 'Aldermoor Veterinary Hospitals',
    retention_years  integer NOT NULL DEFAULT 5     -- clinical records (rule 9)
);
CREATE UNIQUE INDEX business_settings_one_row ON business_settings ((true));

-- 1 the centre (own), 2-3 the other national centres, 4-6 abroad: the five
-- others are third parties, listed so transfers name them.
CREATE TABLE sites (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code    text    NOT NULL UNIQUE,
    name    text    NOT NULL,
    country text    NOT NULL,                     -- ISO 3166 alpha-2
    kind    text    NOT NULL CHECK (kind IN ('own', 'centre', 'abroad'))
);

CREATE TABLE sections (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id integer NOT NULL REFERENCES sites,
    kind    text    NOT NULL CHECK (kind IN ('horse', 'farm', 'domestic'))
);

-- The centre's staff, one layout (core_staff): kind, section and specialty
-- functions of the id. The applications log in with roles of their own.
CREATE TABLE staff (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text    NOT NULL,
    email      text    NOT NULL UNIQUE,
    kind       text    NOT NULL CHECK (kind IN ('vet', 'nurse', 'technician', 'lab', 'carer',
                                                'reception', 'instructor')),
    section_id integer REFERENCES sections,
    specialty  text,
    started_on date    NOT NULL,
    left_on    date
);

CREATE TABLE owners (
    id            integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          text        NOT NULL CHECK (kind IN ('person', 'stable', 'holding', 'clinic')),
    name          text        NOT NULL,
    email         text        NOT NULL,
    phone         text,
    address       text        NOT NULL,
    country       text        NOT NULL,           -- ISO 3166 alpha-2
    registered_at timestamptz NOT NULL
);

-- Herd h is kept by owner h + 1 (a holding); its holding number leads to the
-- keeper through the national registry.
CREATE TABLE herds (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keeper_owner_id integer NOT NULL REFERENCES owners,
    holding_number  text    NOT NULL UNIQUE,
    site_id         integer NOT NULL REFERENCES sites      -- the site that follows it
);

-- food_chain: a horse is food-producing unless excluded (signed, dated, one
-- way); a farm animal food-producing; a domestic animal not-applicable. The
-- natural identifiers are unique when present (a dozen mistyped chips
-- planted: still unique, but no part's load holds them).
CREATE TABLE animals (
    id                     integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species                text        NOT NULL,
    breed                  text        NOT NULL,
    sex                    text        NOT NULL CHECK (sex IN ('female', 'male')),
    born_on                date        NOT NULL,
    name                   text        NOT NULL,
    food_chain             text        NOT NULL
                           CHECK (food_chain IN ('food-producing', 'excluded', 'not-applicable')),
    food_chain_excluded_on date,
    food_chain_excluded_by integer     REFERENCES staff,
    herd_id                integer     REFERENCES herds,
    microchip              text        UNIQUE,
    ueln                   text        UNIQUE,
    passport_number        text        UNIQUE,
    ear_tag                text        UNIQUE,
    registered_at          timestamptz NOT NULL,
    status                 text        NOT NULL DEFAULT 'alive' CHECK (status IN ('alive', 'died')),
    died_at                timestamptz,
    death_kind             text        CHECK (death_kind IN ('natural', 'euthanasia')),
    CHECK ((status = 'died') = (died_at IS NOT NULL)),
    CHECK (food_chain <> 'excluded' OR food_chain_excluded_on IS NOT NULL)
);

-- Dated ownership: a sale ends one row and opens the next; a keeper (a
-- stable, a livery yard, a holding) beside the owner.
CREATE TABLE ownerships (
    animal_id integer     NOT NULL REFERENCES animals,
    owner_id  integer     NOT NULL REFERENCES owners,
    role      text        NOT NULL CHECK (role IN ('owner', 'keeper')),
    from_at   timestamptz NOT NULL,
    until_at  timestamptz,
    PRIMARY KEY (animal_id, owner_id, role, from_at),
    CHECK (until_at IS NULL OR until_at > from_at)
);
CREATE UNIQUE INDEX ownerships_one_current_owner ON ownerships (animal_id)
    WHERE role = 'owner' AND until_at IS NULL;
CREATE INDEX ownerships_owner_idx ON ownerships (owner_id);

CREATE TABLE referring_practices (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    text    NOT NULL,
    address text    NOT NULL,
    country text    NOT NULL,
    email   text    NOT NULL
);

-- Two vets a practice: vet v's practice is core_referring_practice(v).
CREATE TABLE referring_vets (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    practice_id integer NOT NULL REFERENCES referring_practices,
    name        text    NOT NULL,
    email       text    NOT NULL
);

-- --- The medical record ------------------------------------------------------

-- received -> accepted -> closed (the vet's letter: report_sent_at), or declined.
CREATE TABLE referrals (
    id               integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id        integer     NOT NULL REFERENCES animals,
    referring_vet_id integer     NOT NULL REFERENCES referring_vets,
    site_id          integer     NOT NULL REFERENCES sites,          -- the receiving site
    received_at      timestamptz NOT NULL,
    reason           text        NOT NULL,
    state            text        NOT NULL DEFAULT 'received'
                     CHECK (state IN ('received', 'accepted', 'closed', 'declined')),
    decided_at       timestamptz,
    report_sent_at   timestamptz
);
CREATE INDEX referrals_state_idx ON referrals (state, received_at);

-- The hospital stay (D278 answer 6): vet-housing places it in a unit by id.
CREATE TABLE stays (
    id                    integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id             integer     NOT NULL REFERENCES animals,
    site_id               integer     NOT NULL REFERENCES sites,
    section_id            integer     NOT NULL REFERENCES sections,
    admitting_vet_id      integer     NOT NULL REFERENCES staff,
    reason                text        NOT NULL,
    admitted_at           timestamptz NOT NULL,
    discharged_at         timestamptz,
    outcome               text        CHECK (outcome IN ('discharged', 'transferred', 'died')),
    transferred_to_site_id integer    REFERENCES sites,
    CHECK ((discharged_at IS NULL) = (outcome IS NULL)),
    CHECK ((outcome = 'transferred') = (transferred_to_site_id IS NOT NULL))
);
CREATE INDEX stays_current_idx ON stays (section_id) WHERE discharged_at IS NULL;
CREATE INDEX stays_animal_idx ON stays (animal_id);

-- An animal's consultation, or a herd's (a herd visit). open -> closed ->
-- signed, signed by its vet within a day (rule 8). booking_id is
-- vet-scheduling's, by id, unique when present (D317).
CREATE TABLE consultations (
    id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id   integer     REFERENCES animals,
    herd_id     integer     REFERENCES herds,
    site_id     integer     NOT NULL REFERENCES sites,
    section_id  integer     NOT NULL REFERENCES sections,
    vet_id      integer     NOT NULL REFERENCES staff,
    kind        text        NOT NULL
                CHECK (kind IN ('scheduled', 'emergency', 'herd-visit', 'in-hospital')),
    referral_id integer     REFERENCES referrals,
    stay_id     integer     REFERENCES stays,
    booking_id  integer,
    started_at  timestamptz NOT NULL,
    ended_at    timestamptz,
    findings    text,
    state       text        NOT NULL DEFAULT 'open' CHECK (state IN ('open', 'closed', 'signed')),
    signed_at   timestamptz,
    CHECK ((animal_id IS NULL) <> (herd_id IS NULL)),
    CHECK ((kind = 'herd-visit') = (herd_id IS NOT NULL)),
    CHECK (state = 'open' OR ended_at IS NOT NULL),
    CHECK ((state = 'signed') = (signed_at IS NOT NULL))
);
CREATE UNIQUE INDEX consultations_booking_idx ON consultations (booking_id)
    WHERE booking_id IS NOT NULL;
CREATE INDEX consultations_animal_idx ON consultations (animal_id);
CREATE INDEX consultations_state_idx ON consultations (state, started_at);
CREATE INDEX consultations_stay_idx ON consultations (stay_id) WHERE stay_id IS NOT NULL;

-- notifiable: none, A (a category A disease, notified within the hour), other
-- (another listed disease, within the day; D306, rule 7).
CREATE TABLE diagnosis_codes (
    code          text PRIMARY KEY,
    label         text NOT NULL,
    species_group text NOT NULL CHECK (species_group IN ('domestic', 'horse', 'farm', 'any')),
    notifiable    text NOT NULL DEFAULT 'none' CHECK (notifiable IN ('none', 'A', 'other'))
);

CREATE TABLE diagnoses (
    id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id integer     NOT NULL REFERENCES consultations,
    code            text        NOT NULL REFERENCES diagnosis_codes,
    confirmed       boolean     NOT NULL,
    recorded_at     timestamptz NOT NULL
);
CREATE INDEX diagnoses_consultation_idx ON diagnoses (consultation_id);

CREATE TABLE procedures (
    id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id integer     REFERENCES consultations,
    stay_id         integer     REFERENCES stays,
    code            text        NOT NULL,
    lead_staff_id   integer     NOT NULL REFERENCES staff,
    anaesthesia     boolean     NOT NULL,
    performed_at    timestamptz NOT NULL,
    CHECK (consultation_id IS NOT NULL OR stay_id IS NOT NULL)
);
CREATE INDEX procedures_consultation_idx ON procedures (consultation_id);

-- An analysis or an imaging study ordered in a consultation (core_request).
-- requested -> sent -> resulted, or cancelled: by the vet while requested;
-- once sent by the lab only, or the imaging team for imaging, copied back
-- (D315, D324). resulted is the part's fact copied back by a purpose: two
-- places for one fact. Whether a test goes out is the lab's routing (D301).
CREATE TABLE requests (
    id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id integer     NOT NULL REFERENCES consultations,
    animal_id       integer     NOT NULL REFERENCES animals,
    kind            text        NOT NULL CHECK (kind IN ('analysis', 'imaging')),
    code            text        NOT NULL,       -- the lab's test code or machinery's study code
    requested_by    integer     NOT NULL REFERENCES staff,
    priority        text        NOT NULL CHECK (priority IN ('routine', 'urgent')),
    requested_at    timestamptz NOT NULL,
    state           text        NOT NULL DEFAULT 'requested'
                    CHECK (state IN ('requested', 'sent', 'resulted', 'cancelled')),
    sent_at         timestamptz,
    resulted_at     timestamptz,
    cancelled_at    timestamptz,
    CHECK (state <> 'sent' OR sent_at IS NOT NULL),
    CHECK ((state = 'resulted') = (resulted_at IS NOT NULL)),
    CHECK ((state = 'cancelled') = (cancelled_at IS NOT NULL))
);
CREATE INDEX requests_state_idx ON requests (state, requested_at);
CREATE INDEX requests_consultation_idx ON requests (consultation_id);

-- On an animal: what every display and part reads; an infectious alert sends
-- the animal to isolation.
CREATE TABLE alerts (
    id        integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id integer     NOT NULL REFERENCES animals,
    kind      text        NOT NULL CHECK (kind IN ('allergy', 'dangerous', 'infectious', 'other')),
    text      text        NOT NULL,
    from_at   timestamptz NOT NULL,
    until_at  timestamptz,
    CHECK (until_at IS NULL OR until_at > from_at)
);
CREATE INDEX alerts_animal_idx ON alerts (animal_id);

-- An exchange with another centre (D306): a transfer or an examination, out
-- (the centre asking: requested -> sent -> accepted or declined, an accepted
-- examination -> reported) or in (the partner asking: received -> accepted or
-- declined -> reported). exchange_key is the round trip's correlation key; an
-- inbound request carries the partner's patient summary until the animal is
-- registered. Its messages are purpose 4's trace (ops.exchange_messages).
CREATE TABLE exchanges (
    id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direction       text        NOT NULL CHECK (direction IN ('out', 'in')),
    kind            text        NOT NULL CHECK (kind IN ('transfer', 'examination')),
    partner_site_id integer     NOT NULL REFERENCES sites,
    animal_id       integer     REFERENCES animals,
    partner_patient text,
    stay_id         integer     REFERENCES stays,    -- a transfer's stay, ended 'transferred'
    reason          text        NOT NULL,
    exchange_key    uuid        NOT NULL UNIQUE,
    requested_at    timestamptz NOT NULL,
    sent_at         timestamptz,
    state           text        NOT NULL
                    CHECK (state IN ('requested', 'sent', 'received', 'accepted', 'declined',
                                     'reported')),
    accepted_for    date,                           -- the answer: an accepted date, or declined
    answered_at     timestamptz,
    report          text,
    reported_at     timestamptz,
    CHECK (animal_id IS NOT NULL OR partner_patient IS NOT NULL),
    CHECK (direction = 'out' OR state NOT IN ('requested', 'sent')),
    CHECK (direction = 'in' OR state <> 'received')
);
CREATE INDEX exchanges_state_idx ON exchanges (direction, state);

-- --- Medicines ---------------------------------------------------------------

CREATE TABLE medicines (
    id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                     text    NOT NULL,
    authorisation_number     text    NOT NULL UNIQUE,
    atcvet_code              text    NOT NULL,
    form                     text    NOT NULL,
    antimicrobial            boolean NOT NULL,
    controlled               boolean NOT NULL,
    meat_withdrawal_days     integer,   -- null: not authorised for food-producing animals
    milk_withdrawal_days     integer,
    food_chain_horse_allowed boolean NOT NULL
);

-- At load only: stock receipts are out of v0.5.
CREATE TABLE medicine_batches (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_id       integer NOT NULL REFERENCES medicines,
    batch_number      text    NOT NULL,
    site_id           integer NOT NULL REFERENCES sites,
    expires_on        date    NOT NULL,
    quantity_received numeric(12,2) NOT NULL,
    UNIQUE (medicine_id, batch_number)
);

-- issued -> dispensed, expired (an antimicrobial after five days, rule 1, the
-- others after their lines' days) or
-- cancelled.
CREATE TABLE prescriptions (
    id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id integer     NOT NULL REFERENCES consultations,
    animal_id       integer     REFERENCES animals,
    herd_id         integer     REFERENCES herds,
    vet_id          integer     NOT NULL REFERENCES staff,
    issued_at       timestamptz NOT NULL,
    valid_until     timestamptz NOT NULL,
    state           text        NOT NULL DEFAULT 'issued'
                    CHECK (state IN ('issued', 'dispensed', 'expired', 'cancelled')),
    CHECK ((animal_id IS NULL) <> (herd_id IS NULL))
);
CREATE INDEX prescriptions_consultation_idx ON prescriptions (consultation_id);
CREATE INDEX prescriptions_state_idx ON prescriptions (state, valid_until);

-- The withdrawal days as prescribed (the cascade's minimum when cascade,
-- rule 1), and the day the withdrawal ends for a food-producing animal.
CREATE TABLE prescription_lines (
    id                   integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_id      integer       NOT NULL REFERENCES prescriptions,
    medicine_id          integer       NOT NULL REFERENCES medicines,
    dose                 numeric(10,2) NOT NULL,
    unit                 text          NOT NULL,
    frequency_hours      integer       NOT NULL,
    days                 integer       NOT NULL,
    cascade              boolean       NOT NULL DEFAULT false,
    meat_withdrawal_days integer,
    milk_withdrawal_days integer,
    withdrawal_ends_on   date
);
CREATE INDEX prescription_lines_prescription_idx ON prescription_lines (prescription_id);

-- scheduled -> given, missed or cancelled: the rounds' doses for a stay.
CREATE TABLE administrations (
    id                   integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id            integer       NOT NULL REFERENCES animals,
    stay_id              integer       REFERENCES stays,
    prescription_line_id integer       NOT NULL REFERENCES prescription_lines,
    medicine_id          integer       NOT NULL REFERENCES medicines,
    batch_id             integer       REFERENCES medicine_batches,
    quantity             numeric(10,2) NOT NULL,
    scheduled_at         timestamptz   NOT NULL,
    given_at             timestamptz,
    given_by             integer       REFERENCES staff,
    state                text          NOT NULL DEFAULT 'scheduled'
                         CHECK (state IN ('scheduled', 'given', 'missed', 'cancelled')),
    CHECK ((state = 'given') = (given_at IS NOT NULL))
);
CREATE INDEX administrations_due_idx ON administrations (scheduled_at) WHERE state = 'scheduled';
CREATE INDEX administrations_stay_idx ON administrations (stay_id);

-- A supply to the owner (the medicines register's line, rule 2).
CREATE TABLE dispensings (
    id                   integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_line_id integer       NOT NULL REFERENCES prescription_lines,
    batch_id             integer       NOT NULL REFERENCES medicine_batches,
    quantity             numeric(10,2) NOT NULL,
    owner_id             integer       NOT NULL REFERENCES owners,
    dispensed_by         integer       NOT NULL REFERENCES staff,
    dispensed_at         timestamptz   NOT NULL
);
CREATE INDEX dispensings_line_idx ON dispensings (prescription_line_id);

-- --- The displays' board (D287) ---------------------------------------------

-- What a ward display shows of an animal in hospital: its identity (no
-- natural identifier, no owner: rule 10, least data per reader), its current
-- stay, its current alerts and today's administrations (the customer's day).
CREATE VIEW animal_board AS
SELECT a.id AS animal_id, a.name, a.species, a.breed, a.sex,
       s.id AS stay_id, s.section_id, s.admitted_at,
       (SELECT coalesce(string_agg(al.kind || ': ' || al.text, '; ' ORDER BY al.id), '')
          FROM alerts al
         WHERE al.animal_id = a.id AND al.from_at <= now()
           AND (al.until_at IS NULL OR al.until_at > now())) AS alerts,
       (SELECT count(*) FROM administrations ad
         WHERE ad.stay_id = s.id
           AND (ad.scheduled_at AT TIME ZONE b.timezone)::date
               = (now() AT TIME ZONE b.timezone)::date) AS doses_today,
       (SELECT count(*) FROM administrations ad
         WHERE ad.stay_id = s.id AND ad.state = 'given'
           AND (ad.given_at AT TIME ZONE b.timezone)::date
               = (now() AT TIME ZONE b.timezone)::date) AS doses_given_today,
       (SELECT min(ad.scheduled_at) FROM administrations ad
         WHERE ad.stay_id = s.id AND ad.state = 'scheduled') AS next_dose_at
  FROM stays s
  JOIN animals a ON a.id = s.animal_id
 CROSS JOIN business_settings b
 WHERE s.discharged_at IS NULL;

RESET ROLE;
REVOKE CREATE ON SCHEMA public FROM vet;

-- --- Grants (vet-core-domain.md, "Application roles and grants") -------------

-- Writing a table whose id is an identity column needs no privilege on its
-- sequence.

-- The practice software reads every table and writes the record and the
-- people it keeps; never the reference tables (sites, sections, staff,
-- diagnosis codes, medicines, batches).
GRANT SELECT ON ALL TABLES IN SCHEMA public TO vet_app;
GRANT INSERT, UPDATE ON owners, ownerships, animals, herds, referrals, consultations, diagnoses,
                        procedures, requests, stays, alerts, exchanges, prescriptions,
                        prescription_lines, administrations, dispensings
   TO vet_app;
-- A new owner's e-mail and a new animal's natural identifiers are functions
-- of the new id (the core's key functions), so the software takes the id
-- from the sequence first.
GRANT USAGE ON SEQUENCE owners_id_seq, animals_id_seq TO vet_app;

-- The lookup API: animals without the death columns (status, died_at,
-- death_kind), ownerships, owners' id, kind and name (no contact), the stays'
-- census columns (D319).
GRANT SELECT (id, species, breed, sex, born_on, name, food_chain, herd_id, microchip, ueln,
              passport_number, ear_tag, registered_at)
   ON animals TO vet_lookup;
GRANT SELECT ON ownerships TO vet_lookup;
GRANT SELECT (id, kind, name) ON owners TO vet_lookup;
GRANT SELECT (id, animal_id, section_id, admitted_at, discharged_at) ON stays TO vet_lookup;

-- The displays: the board only (vet-housing's housing_unit_board is granted
-- by that part's schema where it lands here).
GRANT SELECT ON animal_board TO vet_display;

-- The back office: every table, contacts included; nothing written. The
-- parts landing here grant theirs in their own schemas.
GRANT SELECT ON ALL TABLES IN SCHEMA public TO vet_reports;
