-- vet-scheduling's data model (v0.5 master spec 9.4; specs/versions/v0.5/
-- vet-scheduling-domain.md, "The data model"; capture W3 items 0 and 2, "W3
-- item 2, revised", spec D408-D414): the centre's rooms and bookable
-- machines, the bookings and the allocations they take, the slot function,
-- the rota and its absences, and the training centre. In the core's
-- database by the scenario's at: (records/clinic), but written to run in a
-- database of its own as well: no foreign key to the core, no grant on its
-- tables, every flow with the core a purpose (O171, O172).
--
-- The database convention (v0.5 capture W2, item 3): gmctl load-data runs
-- this file after the core's schema.sql and load.sql, connected to the same
-- database (psql -d <database>) as the postgres OS user, then data/load.sql
-- with the core's data/keys.sql streamed ahead of it. So this file never
-- creates a database nor connects to one; it creates its roles at top level
-- and names its database :"DBNAME". The login roles' passwords are the
-- game's secrets, set by load-data, never written here.
--
-- Tables in public, prefixed sched_, owned by sched; integer keys GENERATED
-- BY DEFAULT AS IDENTITY, written explicitly by the load, each sequence set
-- after its range (load.sql's end). The core's keys (section, staff,
-- animal, request, exchange, referring practice and vet) and vet-machinery's
-- machines are plain integer columns with no foreign key. Column names
-- follow capture W3 item 0 (a time ends _at, a date _on, a staff member _by).
CREATE ROLE sched NOLOGIN;           -- owns the tables and the slot function
CREATE ROLE sched_app LOGIN;         -- the practice software's scheduling module (pms)
CREATE ROLE sched_reports LOGIN;     -- the periodic reports on the standby (purpose 12)

GRANT CONNECT ON DATABASE :"DBNAME" TO sched_app, sched_reports;

-- The exclusion constraints' integer equality under GiST (PostgreSQL's
-- contrib, in the brick's postgresql-18 package), created as postgres.
CREATE EXTENSION btree_gist;

-- The tables are sched's: it may create them in public for this file only.
GRANT USAGE, CREATE ON SCHEMA public TO sched;
SET ROLE sched;

-- --- Reference ------------------------------------------------------------------

-- One row: the customer's zone and offset (a copy, as the lab's lab_settings:
-- in a database of its own the part keeps it), the booking horizon of the
-- slot function, the no-show delay, the teaching animals' limits, the
-- attendance a certificate needs, the minimum rest (game values, rules 3, 6,
-- 7, 8).
CREATE TABLE sched_settings (
    id                        integer      PRIMARY KEY CHECK (id = 1),
    timezone                  text         NOT NULL,
    utc_offset                integer      NOT NULL,
    horizon_days              integer      NOT NULL DEFAULT 42,
    no_show_minutes           integer      NOT NULL DEFAULT 30,
    teaching_sessions_a_day   integer      NOT NULL DEFAULT 2,
    teaching_hours_a_day      integer      NOT NULL DEFAULT 4,
    teaching_days_before_rest integer      NOT NULL DEFAULT 2,
    certificate_attendance    numeric(3,2) NOT NULL DEFAULT 0.80,
    min_rest_hours            integer      NOT NULL DEFAULT 11
);

-- 1-7 domestic, 8-11 horse (10 the arena), 12-13 farm, 14-16 the training
-- centre (docs/gm.md, "The rooms"). A consultation space takes the section's
-- consultations (D410): domestic 1-4, horse 8, 9, 10, farm 12, 13 (13 the
-- standing-surgery theatre too).
CREATE TABLE sched_rooms (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               text    NOT NULL UNIQUE,
    name               text    NOT NULL,
    kind               text    NOT NULL CHECK (kind IN ('consulting', 'examination', 'arena', 'procedure',
                                                         'theatre', 'classroom', 'practical')),
    section_id         integer,                         -- the core's sections.id; none for training
    consultation_space boolean NOT NULL DEFAULT false,
    seats              integer,
    active             boolean NOT NULL DEFAULT true
);

-- A room's or a machine's opening hours, local times in the customer's zone
-- (sched_settings.timezone), by ISO weekday (1 Monday .. 7 Sunday); closes
-- 24:00 for a machine around the clock.
CREATE TABLE sched_hours (
    resource_kind text    NOT NULL CHECK (resource_kind IN ('room', 'machine')),
    resource_id   integer NOT NULL,
    weekday       integer NOT NULL CHECK (weekday BETWEEN 1 AND 7),
    opens         time    NOT NULL,
    closes        time    NOT NULL,
    PRIMARY KEY (resource_kind, resource_id, weekday),
    CHECK (closes > opens)
);

-- The ten bookable machines, vet-machinery's ids 7-16 (D324): where each is
-- used, its modality, its slot (the grid of its imaging types), the staff
-- it needs (a radiographer or an imaging vet), around the clock or not. No
-- room: the imaging suite is no bookable room.
CREATE TABLE sched_machines (
    machine_id       integer PRIMARY KEY CHECK (machine_id BETWEEN 7 AND 16),
    section_id       integer,                          -- the core's; none when shared by the sections
    room_id          integer REFERENCES sched_rooms,
    name             text    NOT NULL,
    study_kind       text    NOT NULL CHECK (study_kind IN ('ct', 'mri', 'mri-standing', 'radiography',
                                                             'ultrasound', 'scintigraphy')),
    slot_minutes     integer NOT NULL CHECK (slot_minutes > 0),
    operator_kind    text    NOT NULL CHECK (operator_kind IN ('radiographer', 'imaging-vet')),
    around_the_clock boolean NOT NULL DEFAULT false
);

-- The training centre's 16 courses: a session day takes a room of the
-- course's room kind, an instructor, and its teaching animals of its
-- species (dogs for canine, horses for equine; none for the mixed ones).
CREATE TABLE sched_courses (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             text    NOT NULL UNIQUE,
    title            text    NOT NULL,
    audience         text    NOT NULL CHECK (audience IN ('vet', 'nurse', 'student', 'owner', 'handler')),
    species          text    NOT NULL CHECK (species IN ('canine', 'equine', 'mixed')),
    days             integer NOT NULL CHECK (days BETWEEN 1 AND 3),
    hours            integer NOT NULL,
    seats            integer NOT NULL CHECK (seats BETWEEN 8 AND 14),
    teaching_animals integer NOT NULL DEFAULT 0,
    room_kind        text    NOT NULL CHECK (room_kind IN ('classroom', 'practical', 'arena')),
    CHECK (species <> 'mixed' OR teaching_animals = 0)
);

-- The 45 appointment types (docs/gm.md, "The types"): 1-12 consultations
-- (30 minutes in a consultation space of the section, D410), 13-24 imaging
-- (one per section and machine, D372; study_code empty: an imaging booking's
-- study is its request's code), 25-27 surgeries (a theatre of the section,
-- the theatre team), 28-29 blocks (a machine's or a room's), 30-45 a session
-- day of each course. staff: the staff a booking takes, in the slot
-- function's order.
CREATE TABLE sched_types (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             text    NOT NULL UNIQUE,
    name             text    NOT NULL,
    kind             text    NOT NULL CHECK (kind IN ('consultation', 'imaging', 'surgery', 'block', 'session')),
    section_id       integer,                          -- the core's
    duration_minutes integer NOT NULL CHECK (duration_minutes > 0),
    room_kind        text    CHECK (room_kind IN ('consultation', 'theatre', 'classroom', 'practical', 'arena')),
    study_code       text,
    machine_id       integer REFERENCES sched_machines,
    staff            text    CHECK (staff IN ('vet', 'operator', 'theatre-team', 'instructor')),
    course_id        integer REFERENCES sched_courses,
    CHECK ((kind = 'session') = (course_id IS NOT NULL)),
    CHECK (kind <> 'imaging' OR machine_id IS NOT NULL),
    CHECK (kind <> 'consultation' OR duration_minutes = 30)
);

-- --- Bookings and allocations ------------------------------------------------------

-- A consultation, an imaging study, a theatre plan, a block or a session
-- day. The animal is the core's patient (none for a block, a session day, or
-- an inbound examination before its animal is registered); a request, an
-- exchange or a session names what it books. booked -> arrived, no-show or
-- cancelled; a block or a session day booked -> held, or cancelled.
CREATE TABLE sched_bookings (
    id            integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_id       integer     NOT NULL REFERENCES sched_types,
    kind          text        NOT NULL CHECK (kind IN ('consultation', 'imaging', 'surgery', 'block', 'session')),
    animal_id     integer,                              -- the core's animals.id, a patient
    section_id    integer,                              -- the core's
    starts_at     timestamptz NOT NULL,
    ends_at       timestamptz NOT NULL,
    state         text        NOT NULL DEFAULT 'booked'
                  CHECK (state IN ('booked', 'arrived', 'no-show', 'cancelled', 'held')),
    source        text        NOT NULL CHECK (source IN ('phone', 'desk', 'follow-up', 'referral', 'request',
                                                         'exchange', 'planned')),
    request_id    integer,                              -- the core's requests.id, an imaging study
    exchange_id   integer,                              -- the core's exchanges.id, an inbound examination
    session_id    integer,
    booked_at     timestamptz NOT NULL,
    booked_by     integer,                              -- the core's staff.id
    notes         text,
    arrived_at    timestamptz,
    cancelled_at  timestamptz,
    cancel_reason text        CHECK (cancel_reason IN ('owner', 'clinic', 'deceased', 'moved')),
    CHECK (ends_at > starts_at),
    CHECK ((state = 'cancelled') = (cancelled_at IS NOT NULL)),
    CHECK ((state = 'cancelled') = (cancel_reason IS NOT NULL)),
    CHECK (state <> 'arrived' OR arrived_at IS NOT NULL)
);
CREATE INDEX sched_bookings_starts_idx ON sched_bookings (starts_at);
CREATE INDEX sched_bookings_animal_idx ON sched_bookings (animal_id);
-- book-requests' live-booking check (without it, trap T126)
CREATE INDEX sched_bookings_request_idx ON sched_bookings (request_id);
CREATE INDEX sched_bookings_exchange_idx ON sched_bookings (exchange_id);

-- One row per resource a booking takes, exactly one of a staff member, a
-- room, a machine or a teaching animal, over [starts_at, ends_at); released
-- when its booking is cancelled (the trigger below). A past allocation stays
-- live, the record of who was where.
CREATE TABLE sched_allocations (
    id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id  integer     NOT NULL REFERENCES sched_bookings,
    staff_id    integer,                                -- the core's staff.id
    room_id     integer     REFERENCES sched_rooms,
    machine_id  integer     REFERENCES sched_machines,
    animal_id   integer,                                -- the core's animals.id, a teaching animal
    role        text        NOT NULL CHECK (role IN ('vet', 'nurse', 'surgeon', 'anaesthetist', 'operator',
                                                     'instructor', 'room', 'machine', 'teaching')),
    starts_at   timestamptz NOT NULL,
    ends_at     timestamptz NOT NULL,
    during      tstzrange   GENERATED ALWAYS AS (tstzrange(starts_at, ends_at, '[)')) STORED,
    released_at timestamptz,
    CHECK (num_nonnulls(staff_id, room_id, machine_id, animal_id) = 1),
    CHECK (ends_at > starts_at),
    -- One place at a time (rule 1): no resource allocated twice at once.
    CONSTRAINT sched_allocations_staff_excl EXCLUDE USING gist (staff_id WITH =, during WITH &&)
        WHERE (staff_id IS NOT NULL AND released_at IS NULL),
    CONSTRAINT sched_allocations_room_excl EXCLUDE USING gist (room_id WITH =, during WITH &&)
        WHERE (room_id IS NOT NULL AND released_at IS NULL),
    CONSTRAINT sched_allocations_machine_excl EXCLUDE USING gist (machine_id WITH =, during WITH &&)
        WHERE (machine_id IS NOT NULL AND released_at IS NULL),
    CONSTRAINT sched_allocations_animal_excl EXCLUDE USING gist (animal_id WITH =, during WITH &&)
        WHERE (animal_id IS NOT NULL AND released_at IS NULL)
);
CREATE INDEX sched_allocations_booking_idx ON sched_allocations (booking_id);

-- --- The rota ----------------------------------------------------------------------

-- Each staff member's shifts by the rota's pattern (vet-core's core_shifts,
-- one formula with sched.rota.publish's): planned to the end of the seventh
-- week ahead, published (published_at) to the end of the week after next
-- (D411); clocked in and out, an on-call shift only on a call-out.
CREATE TABLE sched_shifts (
    id             integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id       integer     NOT NULL,                -- the core's staff.id
    section_id     integer,                             -- the core's; none for imaging, the lab, reception, training
    kind           text        NOT NULL CHECK (kind IN ('day', 'late', 'night', 'on-call')),
    starts_at      timestamptz NOT NULL,
    ends_at        timestamptz NOT NULL,
    clocked_in_at  timestamptz,
    clocked_out_at timestamptz,
    published_at   timestamptz,
    CHECK (ends_at > starts_at),
    CHECK (clocked_out_at IS NULL OR clocked_in_at IS NOT NULL)
);
-- sched.rota.publish's idempotence (without it, trap T108)
CREATE UNIQUE INDEX sched_shifts_staff_start_key ON sched_shifts (staff_id, starts_at);
CREATE INDEX sched_shifts_starts_idx ON sched_shifts (starts_at);

-- An absence's kind only, never a reason (rule 4): from_at to until_at.
CREATE TABLE sched_absences (
    id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id    integer     NOT NULL,                   -- the core's staff.id
    kind        text        NOT NULL CHECK (kind IN ('leave', 'training', 'absent')),
    from_at     timestamptz NOT NULL,
    until_at    timestamptz NOT NULL,
    recorded_at timestamptz NOT NULL,
    recorded_by integer,                                -- the core's staff.id
    note        text,
    CHECK (until_at > from_at)
);
CREATE INDEX sched_absences_staff_idx ON sched_absences (staff_id, from_at);

-- --- The training centre ----------------------------------------------------------

-- A course's run, one to three consecutive weekdays, each a booking (kind
-- session) with its allocations. planned -> open (eight weeks ahead) ->
-- full -> running -> held, or cancelled.
CREATE TABLE sched_sessions (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id integer NOT NULL REFERENCES sched_courses,
    first_on  date    NOT NULL,
    last_on   date    NOT NULL,
    led_by    integer NOT NULL,                         -- the core's staff.id, an instructor
    state     text    NOT NULL CHECK (state IN ('planned', 'open', 'full', 'running', 'held', 'cancelled')),
    CHECK (last_on >= first_on)
);

-- People, never staff: a vet, nurse or student from outside, an owner, a
-- handler or groom; a vet may be one of the core's referring vets.
CREATE TABLE sched_trainees (
    id               integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             text        NOT NULL,
    email            text,
    phone            text,
    kind             text        NOT NULL CHECK (kind IN ('vet', 'nurse', 'student', 'owner', 'handler')),
    practice_id      integer,                           -- the core's referring_practices.id
    referring_vet_id integer,                           -- the core's referring_vets.id
    registered_at    timestamptz NOT NULL
);

-- enrolled or waitlisted -> attended (certified at 80 % of the hours) or
-- no-show; cancelled.
CREATE TABLE sched_enrolments (
    id                 integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id         integer      NOT NULL REFERENCES sched_sessions,
    trainee_id         integer      NOT NULL REFERENCES sched_trainees,
    enrolled_at        timestamptz  NOT NULL,
    state              text         NOT NULL CHECK (state IN ('enrolled', 'waitlisted', 'attended', 'no-show',
                                                              'cancelled')),
    hours_attended     numeric(4,1),
    certificate_number text         UNIQUE,
    issued_at          timestamptz,
    UNIQUE (session_id, trainee_id),
    CHECK ((certificate_number IS NULL) = (issued_at IS NULL))
);

-- --- Logic in the database ------------------------------------------------------------

-- The next free slots of a type from `after` (D412; capture W3 item 2): the
-- type's resource (a consultation space, a theatre of its section, the
-- course's room, or its machine) open then (sched_hours, local times in the
-- customer's zone), on the grid of the type's duration from the opening (a
-- surgery's on the half-hour; a session day at 09:00),
-- ending within the horizon (now() + horizon_days); the staff the type takes
-- on a shift covering the slot (planned or published, D411), on no absence
-- over it; no live allocation of any of them over it (the GiST indexes of the
-- exclusion constraints); for a session day the course's teaching animals of
-- its species free within their limits (docs/gm.md, "The slot function").
-- staff_ids in the type's order: the vet; the operator; the surgeon, the
-- anaesthetist, the nurse; the instructor. It returns no teaching animal
-- (the caller takes the lowest ids free, the exclusion constraint its
-- guard) and no slot for a block type (blocks are inserted directly). The
-- staff layout is the core's (core_staff's CASE, copied: the two texts are
-- one formula, D412), never read from the core's staff.
CREATE FUNCTION sched_free_slots(type_id integer, after timestamptz, how_many integer DEFAULT 1)
  RETURNS TABLE (starts_at timestamptz, ends_at timestamptz, staff_ids integer[], room_id integer,
                 machine_id integer)
  LANGUAGE sql STABLE SET search_path = public, pg_temp AS $fn$
WITH st AS (
  SELECT timezone, now() + horizon_days * interval '1 day' AS horizon, teaching_sessions_a_day AS sessions,
         teaching_hours_a_day AS hours, teaching_days_before_rest AS run
    FROM sched_settings WHERE id = 1),
ty AS (
  SELECT t.id, t.kind, t.section_id, t.duration_minutes * interval '1 minute' AS dur,
         CASE WHEN t.kind = 'surgery' THEN interval '30 minutes' ELSE t.duration_minutes * interval '1 minute' END AS step,
         t.room_kind, t.staff,
         t.machine_id, c.species, coalesce(c.teaching_animals, 0) AS animals, c.room_kind AS course_room,
         m.operator_kind
    FROM sched_types AS t
    LEFT JOIN sched_courses AS c ON c.id = t.course_id
    LEFT JOIN sched_machines AS m ON m.machine_id = t.machine_id
   WHERE t.id = sched_free_slots.type_id AND t.kind <> 'block'),
-- The core's staff layout (vet-core core_staff, D324, D327).
layout AS (
  SELECT n AS id,
         CASE WHEN n BETWEEN 1 AND 28 OR n IN (79, 80) THEN 'vet'
              WHEN n BETWEEN 29 AND 51 THEN CASE WHEN n % 3 = 0 THEN 'technician' ELSE 'nurse' END
              WHEN n BETWEEN 52 AND 56 THEN 'technician'
              WHEN n BETWEEN 57 AND 66 THEN 'carer'
              WHEN n BETWEEN 67 AND 70 THEN 'reception'
              WHEN n BETWEEN 71 AND 78 THEN 'lab'
              WHEN n BETWEEN 81 AND 85 THEN 'instructor' END AS kind,
         CASE WHEN n BETWEEN 1 AND 10 OR n BETWEEN 29 AND 36 OR n BETWEEN 57 AND 60 THEN 1
              WHEN n BETWEEN 11 AND 17 OR n BETWEEN 37 AND 42 OR n BETWEEN 61 AND 62 THEN 2
              WHEN n BETWEEN 18 AND 25 OR n BETWEEN 43 AND 51 OR n BETWEEN 63 AND 66 THEN 3 END AS section_id,
         CASE WHEN n BETWEEN 1 AND 10
                   THEN (ARRAY['surgery', 'internal medicine', 'surgery', 'anaesthesia',
                               'reproduction', 'internal medicine', 'surgery', 'reproduction',
                               'internal medicine', 'anaesthesia'])[n]
              WHEN n BETWEEN 11 AND 17
                   THEN (ARRAY['herd health', 'herd health', 'surgery', 'reproduction',
                               'herd health', 'internal medicine', 'reproduction'])[n - 10]
              WHEN n BETWEEN 18 AND 25
                   THEN (ARRAY['internal medicine', 'surgery', 'emergency and critical care',
                               'anaesthesia', 'surgery', 'internal medicine',
                               'emergency and critical care', 'dermatology'])[n - 17]
              WHEN n BETWEEN 26 AND 28 THEN 'diagnostic imaging'
              WHEN n BETWEEN 52 AND 55 THEN 'radiography'
              WHEN n = 56 THEN 'biomedical engineering'
              WHEN n BETWEEN 79 AND 80 THEN 'clinical pathology'
              WHEN n BETWEEN 81 AND 85 THEN 'teaching' END AS specialty
    FROM generate_series(1, 85) AS n),
res AS (
  SELECT r.id AS room_id, NULL::integer AS machine_id, 'room'::text AS rkind, r.id AS rid
    FROM ty, sched_rooms AS r
   WHERE ty.machine_id IS NULL AND r.active
     AND CASE ty.kind WHEN 'consultation' THEN r.consultation_space AND r.section_id = ty.section_id
                      WHEN 'surgery' THEN r.kind = 'theatre' AND r.section_id = ty.section_id
                      WHEN 'session' THEN r.kind = ty.course_room ELSE false END
  UNION ALL
  SELECT NULL, m.machine_id, 'machine', m.machine_id
    FROM ty JOIN sched_machines AS m ON m.machine_id = ty.machine_id),
-- Every slot of the resources' hours from `after` to the horizon, in time
-- order, the resource free (its exclusion constraint's index).
cand AS (
  SELECT res.room_id, res.machine_id, x.s, x.s + ty.dur AS e
    FROM st, ty, res
    JOIN sched_hours AS h ON h.resource_kind = res.rkind AND h.resource_id = res.rid,
         generate_series((sched_free_slots.after AT TIME ZONE st.timezone)::date,
                         (st.horizon AT TIME ZONE st.timezone)::date, interval '1 day') AS d,
         -- a session day runs 09:00-16:00 (the arena opens at 08:00)
         LATERAL generate_series((d::date + CASE WHEN ty.kind = 'session' THEN greatest(h.opens, time '09:00')
                                                 ELSE h.opens END) AT TIME ZONE st.timezone,
                                 (d::date + h.closes) AT TIME ZONE st.timezone - ty.dur, ty.step) AS x (s)
   WHERE h.weekday = extract(isodow FROM d)
     AND x.s >= sched_free_slots.after AND x.s + ty.dur <= st.horizon
     AND NOT EXISTS (SELECT 1 FROM sched_allocations AS a
                      WHERE a.room_id = res.room_id AND a.released_at IS NULL
                        AND a.during && tstzrange(x.s, x.s + ty.dur, '[)'))
     AND NOT EXISTS (SELECT 1 FROM sched_allocations AS a
                      WHERE a.machine_id = res.machine_id AND a.released_at IS NULL
                        AND a.during && tstzrange(x.s, x.s + ty.dur, '[)'))
   ORDER BY x.s, res.room_id, res.machine_id),
-- Per slot, in time order (so the LIMIT stops the search): the staff the
-- type may take who are free over [s, e): on a shift covering it (an
-- operator on any shift, on-call included; the others on a day, late or
-- night shift), on no absence over it, with no live allocation over it.
pick AS (
  SELECT c.s, c.e, c.room_id, c.machine_id,
         CASE ty.staff
           WHEN 'vet' THEN ARRAY[fs.vets[1]]
           WHEN 'operator' THEN ARRAY[fs.operators[1]]
           WHEN 'instructor' THEN ARRAY[fs.instructors[1]]
           WHEN 'theatre-team' THEN ARRAY[fs.surgeons[1],
                                          (SELECT v FROM unnest(fs.anaesthetists) AS v
                                            WHERE v IS DISTINCT FROM fs.surgeons[1] LIMIT 1),
                                          fs.nurses[1]]
         END AS staff_ids,
         ta.animals_free
    FROM cand AS c CROSS JOIN ty
   CROSS JOIN LATERAL (
     SELECT array_agg(p.id ORDER BY p.id) FILTER (WHERE p.kind = 'vet') AS vets,
            array_agg(p.id ORDER BY p.id) FILTER (WHERE p.kind = 'vet' AND p.specialty = 'surgery') AS surgeons,
            array_agg(p.id ORDER BY p.specialty = 'anaesthesia' DESC, p.id) FILTER (WHERE p.kind = 'vet')
                AS anaesthetists,
            array_agg(p.id ORDER BY p.id) FILTER (WHERE p.kind = 'nurse') AS nurses,
            array_agg(p.id ORDER BY p.id) FILTER (WHERE p.kind <> 'vet' OR p.section_id IS NULL) AS operators,
            array_agg(p.id ORDER BY p.id) FILTER (WHERE p.kind = 'instructor') AS instructors
       FROM layout AS p
      WHERE CASE ty.staff
              WHEN 'vet' THEN p.kind = 'vet' AND p.section_id = ty.section_id
              WHEN 'theatre-team' THEN p.kind IN ('vet', 'nurse') AND p.section_id = ty.section_id
              WHEN 'operator' THEN p.specialty = CASE ty.operator_kind WHEN 'radiographer' THEN 'radiography'
                                                                       ELSE 'diagnostic imaging' END
              WHEN 'instructor' THEN p.kind = 'instructor' ELSE false END
        AND EXISTS (SELECT 1 FROM sched_shifts AS sh
                     WHERE sh.staff_id = p.id AND sh.starts_at <= c.s AND sh.ends_at >= c.e
                       AND (sh.kind <> 'on-call' OR ty.staff = 'operator'))
        AND NOT EXISTS (SELECT 1 FROM sched_absences AS ab
                         WHERE ab.staff_id = p.id AND ab.from_at < c.e AND ab.until_at > c.s)
        AND NOT EXISTS (SELECT 1 FROM sched_allocations AS a
                         WHERE a.staff_id = p.id AND a.released_at IS NULL
                           AND a.during && tstzrange(c.s, c.e, '[)'))) AS fs
   -- for a session day: the course's teaching animals of its species free
   -- from an hour after its start for two hours, within their limits: two
   -- sessions and four hours a local day, a rest day after two days in a row
   CROSS JOIN LATERAL (
     SELECT count(*) AS animals_free
       FROM st AS l,
            generate_series(CASE ty.species WHEN 'canine' THEN 1 ELSE 14601 END,
                            CASE ty.species WHEN 'canine' THEN 12 ELSE 14608 END) AS an,
            LATERAL (SELECT (c.s AT TIME ZONE l.timezone)::date AS d) AS dd
      WHERE ty.kind = 'session' AND ty.animals > 0
        AND NOT EXISTS (SELECT 1 FROM sched_allocations AS a
                         WHERE a.animal_id = an AND a.released_at IS NULL
                           AND a.during && tstzrange(c.s + interval '1 hour', c.s + interval '3 hours', '[)'))
        AND (SELECT count(*) < l.sessions
                    AND coalesce(sum(upper(a.during) - lower(a.during)), interval '0') + interval '2 hours'
                        <= l.hours * interval '1 hour'
               FROM sched_allocations AS a
              WHERE a.animal_id = an AND a.released_at IS NULL
                AND a.during && tstzrange(dd.d AT TIME ZONE l.timezone, (dd.d + 1) AT TIME ZONE l.timezone, '[)'))
        AND NOT EXISTS (
              SELECT 1 FROM generate_series(-l.run, 0) AS k
               WHERE (SELECT count(*) FROM generate_series(k, k + l.run) AS j
                       WHERE j = 0 OR EXISTS (
                             SELECT 1 FROM sched_allocations AS a
                              WHERE a.animal_id = an AND a.released_at IS NULL
                                AND a.during && tstzrange((dd.d + j) AT TIME ZONE l.timezone,
                                                          (dd.d + j + 1) AT TIME ZONE l.timezone, '[)')))
                     > l.run)) AS ta)
SELECT p.s, p.e, p.staff_ids, p.room_id, p.machine_id
  FROM pick AS p, ty
 WHERE p.staff_ids IS NOT NULL AND array_position(p.staff_ids, NULL) IS NULL
   AND (ty.kind <> 'session' OR ty.animals = 0 OR p.animals_free >= ty.animals)
 ORDER BY p.s, p.room_id, p.machine_id
 LIMIT greatest(sched_free_slots.how_many, 0)
$fn$;

-- A cancelled booking frees its resources at once (rule 6).
CREATE FUNCTION sched_release_allocations() RETURNS trigger
  LANGUAGE plpgsql SET search_path = public, pg_temp AS $fn$
BEGIN
    UPDATE sched_allocations SET released_at = now() WHERE booking_id = NEW.id AND released_at IS NULL;
    RETURN NULL;
END
$fn$;
CREATE TRIGGER sched_release AFTER UPDATE OF state ON sched_bookings
    FOR EACH ROW WHEN (NEW.state = 'cancelled') EXECUTE FUNCTION sched_release_allocations();

RESET ROLE;
REVOKE CREATE ON SCHEMA public FROM sched;

