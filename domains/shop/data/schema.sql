-- The shop domain's data model (master spec 6.8, 9): Tarnbeck Outdoor's
-- database as v0.4 knows it, derived from tarnbeck-outdoor-shop's data
-- file. Copied into a scenario, this file and load.sql (in that order)
-- make the database node's data file, which gmctl load-data streams into
--   psql -X -q -v ON_ERROR_STOP=1 -d postgres
-- run as the postgres OS user; the file creates its own roles and
-- database (capture W1, item 0: top-level CREATE ROLE and CREATE DATABASE
-- lines). The login roles' passwords are the game's secrets, set by
-- load-data, never written here.
--
-- The roles and grants are master spec 9.7's rows on db (access model
-- 9.1); the reporting instance's roles (bi_etl, bi_reader) are the sales
-- reporting purpose's material, not the domain's.
CREATE ROLE shop NOLOGIN;          -- owns the business tables
CREATE ROLE shop_app LOGIN;        -- the web shop (producer, through the pooler)
CREATE ROLE shop_reports LOGIN;    -- the back office (direct)
CREATE ROLE shop_etl LOGIN;        -- the hourly roll-up's source; reporting's user mapping
CREATE ROLE shop_crm LOGIN;        -- the win-back and mailing jobs
CREATE ROLE shop_customs LOGIN;    -- the export declaration jobs
CREATE ROLE customs_gw LOGIN;      -- the customs gateway's callback
CREATE ROLE shop_refresh LOGIN;    -- the hourly refresh of popular_products
CREATE DATABASE shop OWNER shop;

\connect shop
SET ROLE shop;

-- --- The business ------------------------------------------------------------

-- One row, written by load.sql from load-data's psql variables (8.5, 9.2):
-- the customer's zone (Etc/GMT-N for UTC+N) and its offset, and the hours
-- marketing mail may reach a recipient, in the recipient's local time.
CREATE TABLE business_settings (
    timezone          text    NOT NULL,
    utc_offset_hours  integer NOT NULL,
    mail_window_start time    NOT NULL DEFAULT '08:00',
    mail_window_end   time    NOT NULL DEFAULT '21:00'
);
CREATE UNIQUE INDEX business_settings_one_row ON business_settings ((true));

-- marketing_opt_in is the web shop's current state, kept beside the
-- consent history; the history is the truth (9.3).
CREATE TABLE customers (
    id               integer       PRIMARY KEY,
    name             text          NOT NULL,
    email            text          NOT NULL,
    address          text          NOT NULL,
    country          text          NOT NULL,   -- ISO 3166 alpha-2
    timezone         text          NOT NULL,   -- Etc/GMT-N for UTC+N
    marketing_opt_in boolean       NOT NULL DEFAULT false,
    created_at       timestamptz   NOT NULL,
    last_order_at    timestamptz,              -- older orders are archived away
    lifetime_value   numeric(12,2) NOT NULL DEFAULT 0
);

-- Every grant and withdrawal of a consent. purpose: marketing-email;
-- source: checkout, unsubscribe-link or support. A customer may be mailed
-- at a moment when their latest marketing-email event at or before it is
-- a grant.
CREATE TABLE consent_events (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer     NOT NULL REFERENCES customers (id),
    purpose     text        NOT NULL,
    granted     boolean     NOT NULL,
    at          timestamptz NOT NULL,
    source      text        NOT NULL
);

CREATE TABLE products (
    id       integer       PRIMARY KEY,
    sku      text          NOT NULL UNIQUE,
    name     text          NOT NULL,
    category text          NOT NULL,
    price    numeric(10,2) NOT NULL,
    stock    integer       NOT NULL,
    sold     integer       NOT NULL DEFAULT 0
);

-- status: paid, packed, shipped, invoiced. The warehouse's status update
-- sets packed_at and shipped_at; ship_country is the customer's country
-- unless the order goes elsewhere.
CREATE TABLE orders (
    id           integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  integer       NOT NULL REFERENCES customers (id),
    placed_at    timestamptz   NOT NULL,
    status       text          NOT NULL,
    total        numeric(10,2) NOT NULL,
    updated_at   timestamptz   NOT NULL,
    packed_at    timestamptz,
    shipped_at   timestamptz,
    ship_country text          NOT NULL    -- ISO 3166 alpha-2
);

CREATE TABLE order_lines (
    id           bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     integer       NOT NULL REFERENCES orders (id),
    product_id   integer       NOT NULL REFERENCES products (id),
    sku          text          NOT NULL,   -- the product as sold
    product_name text          NOT NULL,
    quantity     integer       NOT NULL,
    unit_price   numeric(10,2) NOT NULL,
    vat_rate     numeric(4,2)  NOT NULL,
    line_total   numeric(10,2) NOT NULL,
    created_at   timestamptz   NOT NULL
);

-- The carriers' delivery events, stored as received; a resent event is
-- stored once.
CREATE TABLE delivery_events (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    uuid        NOT NULL UNIQUE,   -- the carrier's id of the event
    order_id    integer     NOT NULL,
    status      text        NOT NULL,
    received_at timestamptz NOT NULL
);

-- The destinations outside the customs union: an order shipped to one is
-- declared to the customs gateway within two hours of being packed.
CREATE TABLE export_countries (
    country text PRIMARY KEY               -- ISO 3166 alpha-2
);

-- --- The purposes' tables (9.6) ----------------------------------------------

CREATE TABLE campaigns (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code      text    NOT NULL UNIQUE,
    segment   text    NOT NULL,            -- winback: last order 60 to 365 days old
    starts_on date    NOT NULL,
    ends_on   date    NOT NULL,
    active    boolean NOT NULL DEFAULT false
);

CREATE TABLE leads (
    campaign_id  integer       NOT NULL REFERENCES campaigns (id),
    customer_id  integer       NOT NULL REFERENCES customers (id),
    score        numeric(6,2)  NOT NULL,
    extracted_at timestamptz   NOT NULL,
    UNIQUE (campaign_id, customer_id)
);

-- Mail "handed to the provider": a row is a mail sent. template:
-- order-shipped (transactional, with order_id) or a campaign's template
-- (marketing, with campaign_id).
CREATE TABLE mail_outbox (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer     NOT NULL REFERENCES customers (id),
    email       text        NOT NULL,
    template    text        NOT NULL,
    campaign_id integer     REFERENCES campaigns (id),
    order_id    integer     REFERENCES orders (id),
    payload     jsonb       NOT NULL,
    sent_at     timestamptz NOT NULL
);

-- Export declarations sent to the customs gateway, keyed by the order.
CREATE TABLE customs_outbox (
    id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        integer     NOT NULL REFERENCES orders (id),
    payload         jsonb       NOT NULL,
    sent_at         timestamptz NOT NULL,
    idempotency_key text        NOT NULL UNIQUE
);

-- The gateway's answers, written by its callback. status: accepted (with
-- the movement reference) or rejected (with the reason).
CREATE TABLE customs_acks (
    outbox_id   bigint      NOT NULL REFERENCES customs_outbox (id),
    status      text        NOT NULL,
    reference   text,
    reason      text,
    received_at timestamptz NOT NULL
);

-- Escalations: a declaration rejected, or unacknowledged 30 minutes after
-- sending.
CREATE TABLE incidents (
    id        bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source    text        NOT NULL,
    ref       text        NOT NULL,
    opened_at timestamptz NOT NULL,
    reason    text        NOT NULL
);

-- The run ledger the jobs on the shop's database write themselves.
CREATE TABLE etl_runs (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job          text        NOT NULL,
    started_at   timestamptz NOT NULL,
    finished_at  timestamptz,
    rows_read    bigint,
    rows_written bigint,
    watermark    timestamptz
);

-- --- The web shop's best sellers ---------------------------------------------

-- Each category's 24 best sellers over the last seven days, for the
-- catalogue pages; refreshed every hour by the database node's crontab.
-- Refreshing runs the query as the view's owner, so shop_refresh needs
-- MAINTAIN on the view and nothing on its inputs.
CREATE MATERIALIZED VIEW popular_products AS
SELECT category, rank, product_id, sku, name, price, units
  FROM (SELECT p.category,
               row_number() OVER (PARTITION BY p.category
                                  ORDER BY sum(l.quantity) DESC, p.id) AS rank,
               p.id AS product_id, p.sku, p.name, p.price, sum(l.quantity) AS units
          FROM order_lines l JOIN products p ON p.id = l.product_id
         WHERE l.created_at >= now() - interval '7 days'
         GROUP BY p.id) AS ranked
 WHERE rank <= 24
  WITH NO DATA;

-- --- Indexes -----------------------------------------------------------------

CREATE INDEX orders_customer_id_idx ON orders (customer_id);
CREATE INDEX orders_placed_at_idx ON orders (placed_at);
CREATE INDEX orders_packed_at_idx ON orders (packed_at);
CREATE INDEX orders_shipped_at_idx ON orders (shipped_at);
CREATE INDEX order_lines_order_id_idx ON order_lines (order_id);
CREATE INDEX delivery_events_received_at_idx ON delivery_events (received_at);
CREATE INDEX consent_events_customer_id_at_idx ON consent_events (customer_id, at);
CREATE INDEX mail_outbox_order_id_idx ON mail_outbox (order_id);
CREATE INDEX mail_outbox_customer_id_idx ON mail_outbox (customer_id);
CREATE INDEX customs_outbox_order_id_idx ON customs_outbox (order_id);
CREATE INDEX customs_acks_outbox_id_idx ON customs_acks (outbox_id);
CREATE UNIQUE INDEX popular_products_category_rank_idx ON popular_products (category, rank);

-- --- Grants (master spec 9.7) ------------------------------------------------

-- Writing a table whose id is an identity column needs no privilege on its
-- sequence; shop_app's sequence grants are tarnbeck's.

-- The web shop: orders, their lines, the stock, the customers' last order,
-- the carriers' events, as in tarnbeck; and the consent history, the
-- opt-in flag, the new order columns and the best sellers.
GRANT SELECT, INSERT, UPDATE ON orders TO shop_app;
GRANT SELECT, INSERT ON order_lines TO shop_app;
GRANT SELECT, UPDATE ON customers, products TO shop_app;
GRANT SELECT, INSERT ON delivery_events TO shop_app;
GRANT SELECT, INSERT ON consent_events TO shop_app;
GRANT SELECT ON popular_products TO shop_app;
GRANT USAGE ON SEQUENCE orders_id_seq, order_lines_id_seq, delivery_events_id_seq,
                        consent_events_id_seq TO shop_app;

-- The back office reads every business table, names and e-mail addresses
-- included; it writes nothing (the roll-up moved to the reporting
-- database).
GRANT SELECT ON business_settings, customers, consent_events, products, orders, order_lines,
                delivery_events, export_countries, campaigns, leads, mail_outbox,
                customs_outbox, customs_acks, incidents, etl_runs, popular_products
   TO shop_reports;

-- The hourly roll-up's source: orders without customer_id (a column
-- grant), their lines, the products.
GRANT SELECT (id, placed_at, status, total, updated_at, packed_at, shipped_at, ship_country)
   ON orders TO shop_etl;
GRANT SELECT ON order_lines, products TO shop_etl;

-- The win-back extraction and the mailing.
GRANT SELECT ON customers, consent_events, orders, campaigns, leads, mail_outbox,
                business_settings
   TO shop_crm;
GRANT INSERT ON leads, mail_outbox, etl_runs TO shop_crm;

-- The export declarations: a customer's name, address and country (and
-- the id that joins them to an order), nothing else of the customer.
GRANT SELECT ON orders, order_lines, export_countries, customs_outbox, customs_acks, incidents
   TO shop_customs;
GRANT SELECT (id, name, address, country) ON customers TO shop_customs;
GRANT INSERT ON customs_outbox, incidents, etl_runs TO shop_customs;

-- The customs gateway's callback.
GRANT SELECT ON customs_outbox TO customs_gw;
GRANT INSERT ON customs_acks TO customs_gw;

-- The hourly refresh of the best sellers (PostgreSQL 17 and later).
GRANT MAINTAIN ON popular_products TO shop_refresh;

RESET ROLE;
